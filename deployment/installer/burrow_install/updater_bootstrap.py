"""Render ``deployment/installer/updater/bootstrap.sh`` (core task 01a1b7b6 stage 4).

The bootstrap installs the host updater (stage 1) on a single-host install
that was rendered before the updater existed. It is POSIX sh, run once as
root by whoever holds the server's root key:

    sudo docker run --rm --entrypoint cat ghcr.io/getburrowing/core:core \\
        /app/updater/bootstrap.sh | sudo sh -s -- --channel stable

Every file it writes comes from the same functions the render uses
(templates.updater_* and bin/burrow-update itself), embedded as quoted
heredocs. Only the install name, the channel, the repositories, the flavour
and the pinned digest are filled in on the host, from the running install.
A test asserts the tracked file equals ``render()``; regenerate it with

    PYTHONPATH=deployment/installer python3 -m burrow_install.updater_bootstrap --write
"""

import os
import shlex
import sys

from . import templates

OUTPUT = os.path.join(os.path.dirname(templates.UPDATER_SOURCE), "bootstrap.sh")

NAME = "@@NAME@@"
CHANNEL = "@@CHANNEL@@"
CORE_REPO = "@@CORE_REPO@@"
ROLLBACK_REPOS = "@@ROLLBACK_REPOS@@"
FLAVOUR = "@@FLAVOUR@@"
WHY = "@@WHY@@"
IMAGE = "@@IMAGE@@"
AUTO = "@@AUTO@@"
UNIT_DIR = "/etc/systemd/system"


class _Named:
    """The unit renderers read only ``plan.name``."""

    name = NAME


def _heredoc(func, text, tag):
    if not text.endswith("\n"):
        raise ValueError(f"{func}: embedded text must end with a newline")
    if any(line == tag for line in text.split("\n")):
        raise ValueError(f"{func}: embedded text contains its heredoc delimiter")
    return f"{func}() {{\n\tcat <<'{tag}'\n{text}{tag}\n}}\n"


def embedded():
    """{shell function name: text} for every file the bootstrap writes."""
    upd = templates.updater_module()
    plan = _Named()
    return {
        "emit_updater": templates.updater_script(),
        "emit_env": templates.updater_env_text(
            NAME,
            {
                "CHANNEL": CHANNEL,
                "CORE_REPO": CORE_REPO,
                "ROLLBACK_REPOS": ROLLBACK_REPOS,
                "FLAVOUR": FLAVOUR,
            },
            WHY,
        ),
        "emit_service": templates.updater_service_unit(plan),
        "emit_timer": templates.updater_timer_unit(plan),
        "emit_path": templates.updater_path_unit(plan, upd.INBOX),
        "emit_override": upd.override_text(IMAGE),
        "emit_status": upd.initial_status(CHANNEL, AUTO),
    }


def render():
    upd = templates.updater_module()
    funcs = "".join(
        _heredoc(name, text, f"BURROW_EOF_{i}") for i, (name, text) in enumerate(embedded().items())
    )
    meeting = " ".join(
        shlex.quote(a) for a in upd.live_meetings_args(templates.UPDATER_MEETING_STALE_HOURS)
    )
    values = {
        "@MEETING_ARGS@": meeting,
        "@REPO_ERE@": shlex.quote(upd.REPO_RE.pattern.replace("(?:", "(")),
        "@PUBLISHED_CORE_REPO@": templates.PUBLISHED_CORE_REPO,
        "@STACK_UNIT@": templates.STACK_UNIT_NAME,
        "@MARKER@": shlex.quote(upd.override_text().split("\n", 1)[0]),
        "@CORE_UID@": str(upd.CORE_UID),
        "@SERVICE_UNIT@": templates.UPDATER_UNIT_NAME,
        "@TIMER_UNIT@": templates.UPDATER_TIMER_NAME,
        "@PATH_UNIT@": templates.UPDATER_PATH_NAME,
        "@UPDATER_BIN@": templates.UPDATER_BIN,
        "@ENV_FILE@": templates.UPDATER_ENV,
        "@BASE@": upd.BASE,
        "@STATE@": upd.STATE,
        "@CONSUMED@": upd.CONSUMED,
        "@CORE_DIR@": upd.CORE_DIR,
        "@STAGING@": upd.STAGING,
        "@INBOX@": upd.INBOX,
        "@OUTBOX@": upd.OUTBOX,
        "@STATUS@": upd.STATUS,
        "@CORE_SERVICE@": upd.CORE_SERVICE,
        "@INSTALL_ROOT@": templates.INSTALL_ROOT,
        "@UNIT_DIR@": UNIT_DIR,
    }
    out = SCRIPT
    for key, value in values.items():
        out = out.replace(key, value)
    # Last, so no placeholder is ever replaced inside an embedded file.
    return out.replace("@FUNCS@", funcs)


SCRIPT = r"""#!/bin/sh
# bootstrap.sh: install the Burrow host updater on an existing single-host
# install (core task 01a1b7b6 stage 4). GENERATED by
# deployment/installer/burrow_install/updater_bootstrap.py from the same
# functions the render uses; do not edit, regenerate.
#
#   sudo docker run --rm --entrypoint cat ghcr.io/getburrowing/core:core \
#       /app/updater/bootstrap.sh | sudo sh -s -- --channel stable
#
# Flags: --channel stable|edge|pinned (default stable; pinned when the running
# core image is a digest or a core-<sha>/play-<sha> tag), --auto-update on|off
# (default on), --dry-run, --root <dir> (tests only: a prefix for every path).
#
# Refuses (exit 1, nothing written): not root; a pre-rename install directory
# that is not a symlink (run burrow-migrate first); `-f` in the stack unit's ExecStart; a
# compose.override.yaml it does not own; a core image that is not core or
# play, or has no registry digest. A live meeting (or one it cannot rule
# out): exit 3, nothing written. It never touches compose.yaml, secrets.env or
# the database (the meeting check is one read-only select).
set -eu
umask 022

PROG=burrow-updater-bootstrap
ROOT=
CHANNEL=
AUTO_FLAG=
DRY_RUN=0

die() { echo "$PROG: refused: $*" >&2; exit 1; }
usage() {
	echo "usage: $PROG [--channel stable|edge|pinned] [--auto-update on|off] [--dry-run]" >&2
	exit 2
}

while [ $# -gt 0 ]; do
	case "$1" in
	--channel) [ $# -ge 2 ] || usage; CHANNEL=$2; shift 2 ;;
	--auto-update) [ $# -ge 2 ] || usage; AUTO_FLAG=$2; shift 2 ;;
	--dry-run) DRY_RUN=1; shift ;;
	--root) [ $# -ge 2 ] || usage; ROOT=${2%/}; shift 2 ;;
	-h|--help) usage ;;
	*) echo "$PROG: unknown argument: $1" >&2; usage ;;
	esac
done
case "$CHANNEL" in ''|stable|edge|pinned) ;; *) echo "$PROG: --channel is stable, edge or pinned" >&2; usage ;; esac
case "$AUTO_FLAG" in ''|on|off) ;; *) echo "$PROG: --auto-update is on or off" >&2; usage ;; esac

INSTALL=$ROOT@INSTALL_ROOT@
UNITS=$ROOT@UNIT_DIR@
STACK=$UNITS/@STACK_UNIT@
OVERRIDE=$INSTALL/compose.override.yaml
MARKER=@MARKER@
REPO_ERE=@REPO_ERE@
SERVICE=@CORE_SERVICE@

# --- checks (nothing is written before every one has passed) ---------------

[ "$(id -u)" = 0 ] || die "run it as root (sudo)"
command -v python3 >/dev/null 2>&1 || die "python3 is missing; the updater needs it"

OLD_ROOT=/opt/suite # legacy name, kept by burrow-migrate
if [ -L "$ROOT$OLD_ROOT" ]; then
	: # a migrated install: the old root is a symlink to @INSTALL_ROOT@
elif [ -d "$ROOT$OLD_ROOT" ]; then
	die "$OLD_ROOT is a directory: this install predates the rename; run burrow-migrate first"
fi
[ -f "$INSTALL/compose.yaml" ] || die "no install at @INSTALL_ROOT@ (compose.yaml missing)"
[ -f "$STACK" ] || die "no @STACK_UNIT@ in @UNIT_DIR@"

EXECSTART=$(grep '^ExecStart=' "$STACK" || true)
case "$EXECSTART" in
*" -f"*|*"--file"*) die "@STACK_UNIT@ passes -f to docker compose, so compose.override.yaml would not be merged" ;;
esac
grep -q '^ExecStart=/usr/bin/docker compose up' "$STACK" ||
	die "@STACK_UNIT@ ExecStart is not \`docker compose up\`"
grep -q '^WorkingDirectory=@INSTALL_ROOT@$' "$STACK" ||
	die "@STACK_UNIT@ does not run in @INSTALL_ROOT@"
if grep -q 'COMPOSE_FILE' "$STACK"; then
	die "@STACK_UNIT@ sets COMPOSE_FILE, so compose.override.yaml would not be merged"
fi

NAME=$(sed -n 's/^Description=Burrow stack (\(.*\))$/\1/p' "$STACK" | head -n 1)
printf '%s\n' "$NAME" | grep -Eq '^[a-z][a-z0-9-]{0,62}$' ||
	die "cannot read the install name from @STACK_UNIT@"

if [ -e "$OVERRIDE" ] || [ -L "$OVERRIDE" ]; then
	[ -f "$OVERRIDE" ] && [ ! -L "$OVERRIDE" ] && [ "$(head -n 1 "$OVERRIDE")" = "$MARKER" ] ||
		die "$OVERRIDE exists and is not the updater's; move it aside and re-run"
fi

# A Docker Hub repository in full: docker shows familiar names (example/x, x).
full_repo() {
	first=${1%%/*}
	case "$1" in
	*/*) case "$first" in *.*|*:*|localhost) echo "$1" ;; *) echo "docker.io/$1" ;; esac ;;
	*) echo "docker.io/library/$1" ;;
	esac
}

IMAGE_REF=$(docker inspect --format '{{.Config.Image}}' "$SERVICE" 2>/dev/null) ||
	die "no $SERVICE container (start the stack first)"
IMAGE_ID=$(docker inspect --format '{{.Image}}' "$SERVICE" 2>/dev/null) ||
	die "cannot inspect $SERVICE"
case "$IMAGE_REF" in
*@sha256:*) REPO=${IMAGE_REF%%@*}; TAG= ; BY_DIGEST=1 ;;
*)
	last=${IMAGE_REF##*/}
	case "$last" in
	*:*) TAG=${last##*:}; REPO=${IMAGE_REF%:*} ;;
	*) TAG=latest; REPO=$IMAGE_REF ;;
	esac
	BY_DIGEST=0
	;;
esac
REPO=$(full_repo "$REPO")
printf '%s\n' "$REPO" | grep -Eq "$REPO_ERE" || die "$SERVICE runs $IMAGE_REF, not a registry image"
case "${REPO##*/}" in
core|suite-core) ;;
*) die "$SERVICE runs $IMAGE_REF, which is not a core image" ;;
esac

# Flavour: the tag's core/play prefix; otherwise (a digest, a legacy `latest`)
# the with-Play switch in the container's environment.
case "$TAG" in
core|core-*) FLAVOUR=core ;;
play|play-*) FLAVOUR=play ;;
*)
	ENVS=$(docker inspect --format '{{range .Config.Env}}{{println .}}{{end}}' "$SERVICE" 2>/dev/null) ||
		die "cannot read the flavour (core or play) of $IMAGE_REF"
	if printf '%s\n' "$ENVS" | grep -qx 'GAME_STREAM_ENABLED=true'; then FLAVOUR=play; else FLAVOUR=core; fi
	;;
esac

ROLLBACK_REPOS=
CORE_REPO=$REPO
if printf '%s\n' "$REPO" | grep -Eq '^docker\.io/[^/]+/suite-core$'; then
	# Legacy Docker Hub install: frozen, no new tags. Follow the published
	# repository; the legacy one stays a rollback target.
	CORE_REPO=@PUBLISHED_CORE_REPO@
	ROLLBACK_REPOS=$REPO
fi

DIGESTS=$(docker image inspect --format '{{range .RepoDigests}}{{println .}}{{end}}' "$IMAGE_ID" 2>/dev/null || true)
RUNNING=
for d in $DIGESTS; do
	dig=${d#*@}
	[ "$(full_repo "${d%%@*}")" = "$REPO" ] || continue
	printf '%s\n' "$dig" | grep -Eq '^sha256:[0-9a-f]{64}$' || continue
	RUNNING="$REPO@$dig"
	break
done
[ -n "$RUNNING" ] || die "$IMAGE_REF has no registry digest for $REPO (not pinnable)"

WHY=
if [ -z "$CHANNEL" ]; then
	CHANNEL=stable
	if [ "$BY_DIGEST" = 1 ] || printf '%s\n' "$TAG" | grep -Eq '^(core|play)-[0-9a-f]{7,40}$'; then
		CHANNEL=pinned
		WHY="the running core image is a digest or a commit tag"
	fi
fi
case "$AUTO_FLAG" in off) AUTO=false ;; *) AUTO=true ;; esac

# The live-meeting check, exactly as bin/burrow-update runs it. A count above
# zero, or no answer, stops here: recreating core would cut the meeting.
COUNT=$(docker @MEETING_ARGS@ 2>/dev/null) || COUNT=
case "$COUNT" in
''|*[!0-9]*)
	echo "$PROG: could not check for a live meeting (is core-postgres up?); nothing written" >&2
	exit 3
	;;
esac
if [ "$COUNT" -gt 0 ]; then
	echo "$PROG: a meeting is live; re-run when it ends. Nothing written." >&2
	exit 3
fi

# --- the files, from the render's own functions -----------------------------

@FUNCS@
fill() {
	sed -e "s|@@NAME@@|$NAME|g" -e "s|@@CHANNEL@@|$CHANNEL|g" \
		-e "s|@@CORE_REPO@@|$CORE_REPO|g" -e "s|@@ROLLBACK_REPOS@@|$ROLLBACK_REPOS|g" \
		-e "s|@@FLAVOUR@@|$FLAVOUR|g" -e "s|@@IMAGE@@|$RUNNING|g" -e "s|\"@@AUTO@@\"|$AUTO|g"
}

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT INT TERM
emit_updater >"$TMP/burrow-update"
if [ -n "$WHY" ]; then
	emit_env | fill | sed "s|@@WHY@@|$WHY|" >"$TMP/updater.env"
else
	emit_env | sed '/@@WHY@@/d' | fill >"$TMP/updater.env"
fi
emit_service | fill >"$TMP/service"
emit_timer | fill >"$TMP/timer"
emit_path | fill >"$TMP/path"
emit_override | fill >"$TMP/override"
emit_status | fill >"$TMP/status"
printf '%s\n' "$RUNNING" >"$TMP/pinned"
printf '{"auto_update": %s}\n' "$AUTO" >"$TMP/settings"

CHANGES=0
APPLY=0

changed() { CHANGES=$((CHANGES + 1)); [ "$APPLY" = 1 ] || echo "$PROG: would write $1"; }

# ensure_dir PATH MODE UID
ensure_dir() {
	if [ ! -d "$1" ]; then
		changed "$1/"
		if [ "$APPLY" = 1 ]; then mkdir -p "$1"; fi
	elif [ -z "$(find "$1" -prune -perm "$2")" ]; then
		changed "$1/ (mode $2)"
	elif [ -z "$ROOT" ] && [ -z "$(find "$1" -prune -user "$3" -group "$3")" ]; then
		changed "$1/ (owner $3)"
	fi
	if [ "$APPLY" = 1 ]; then
		chmod "$2" "$1"
		chown "$3:$3" "$1"
	fi
}

# put SRC DEST MODE: replace DEST when its bytes or mode differ.
put() {
	if [ -f "$2" ] && [ ! -L "$2" ] && cmp -s "$1" "$2" && [ -n "$(find "$2" -prune -perm "$3")" ]; then
		return 0
	fi
	changed "$2"
	if [ "$APPLY" = 1 ]; then
		cp "$1" "$2.tmp.$$"
		chmod "$3" "$2.tmp.$$"
		mv -f "$2.tmp.$$" "$2"
	fi
}

# put_new SRC DEST MODE: only when DEST does not exist (the updater owns it after).
put_new() {
	[ -e "$2" ] || put "$1" "$2" "$3"
}

plan() {
	ensure_dir "$INSTALL/bin" 0755 0
	ensure_dir "$ROOT/etc/burrow-updater" 0755 0
	ensure_dir "$ROOT@BASE@" 0755 0
	ensure_dir "$ROOT@OUTBOX@" 0755 0
	ensure_dir "$ROOT@STATE@" 0700 0
	ensure_dir "$ROOT@CONSUMED@" 0700 0
	ensure_dir "$ROOT@CORE_DIR@" 0700 @CORE_UID@
	ensure_dir "$ROOT@STAGING@" 0700 @CORE_UID@
	ensure_dir "$ROOT@INBOX@" 0700 @CORE_UID@
	put "$TMP/burrow-update" "$INSTALL/@UPDATER_BIN@" 0755
	put "$TMP/updater.env" "$ROOT@ENV_FILE@" 0644
	put "$TMP/service" "$UNITS/@SERVICE_UNIT@" 0644
	put "$TMP/timer" "$UNITS/@TIMER_UNIT@" 0644
	put "$TMP/path" "$UNITS/@PATH_UNIT@" 0644
	put "$TMP/pinned" "$ROOT@STATE@/pinned" 0600
	put_new "$TMP/status" "$ROOT@STATUS@" 0644
	if [ -n "$AUTO_FLAG" ]; then
		put "$TMP/settings" "$ROOT@STATE@/settings" 0600
	fi
	# Last: the override pins the running digest, so the compose up below
	# adds the two mounts without changing the version.
	put "$TMP/override" "$OVERRIDE" 0644
}

plan
if [ "$CHANGES" = 0 ]; then
	echo "$PROG: no changes"
	exit 0
fi
if [ "$DRY_RUN" = 1 ]; then
	echo "$PROG: dry run: $CHANGES change(s), nothing written"
	exit 0
fi
APPLY=1
plan
systemctl daemon-reload
(cd "$INSTALL" && docker compose up -d --no-deps "$SERVICE")
systemctl enable --now @TIMER_UNIT@ @PATH_UNIT@
echo "$PROG: installed: channel $CHANNEL, pinned to $RUNNING; auto-update ${AUTO_FLAG:-on}"
"""


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv
    text = render()
    if args == ["--write"]:
        with open(OUTPUT, "w", encoding="utf-8") as handle:
            handle.write(text)
        return 0
    if args:
        print("usage: python3 -m burrow_install.updater_bootstrap [--write]", file=sys.stderr)
        return 2
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
