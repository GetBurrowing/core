def migrate_script():
    with open(MIGRATE_SCRIPT, encoding="utf-8") as handle:
        return handle.read()


def user_data(plan, install_files, registry_auth, agent_host_env=None):
    """``install_files``: {path relative to the install root: (text, mode)}.

    ``agent_host_env``: the full_machine agent host's env file text (it holds
    AGENT_HOST_TOKEN), or None when ``[agents]`` is not full_machine.
    """
    entries = dict(install_files)
    entries[f"/etc/systemd/system/{STACK_UNIT_NAME}"] = (stack_unit(plan), FILE_MODE)
    entries["bin/burrow-migrate"] = (migrate_script(), EXEC_MODE)
    if plan.backup is not None:
        entries[f"/etc/systemd/system/{BACKUP_UNIT_NAME}"] = (backup_service_unit(plan), FILE_MODE)
        entries[f"/etc/systemd/system/{BACKUP_TIMER_NAME}"] = (backup_timer_unit(plan), FILE_MODE)
    if plan.tls == "internal":
        entries["bin/burrow-root-ca"] = (root_ca_script(plan), EXEC_MODE)
        entries["bin/burrow-ca-bundle"] = (ca_bundle_script(plan), EXEC_MODE)
    if plan.agents == "full_machine":
        entries.update(agents.full_machine_files(plan, agent_host_env))
    if registry_auth is not None:
        entries["/root/.docker/config.json"] = (_ensure_newline(registry_auth), SECRET_MODE)

    write_files = []
    for rel in sorted(entries, key=lambda r: _abs(r)):
        text, mode = entries[rel]
        write_files.append(
            {
                "path": _abs(rel),
                "owner": "root:root",
                "permissions": f"0{mode:o}",
                "content": Literal(text),
            }
        )

    mkdirs = [f"{INSTALL_ROOT}/postgres-init"]
    if plan.host_files:
        mkdirs.append(f"{INSTALL_ROOT}/models")
    runcmd = [["mkdir", "-p", *mkdirs]]
    if plan.tls == "internal":
        runcmd.append([f"{INSTALL_ROOT}/bin/burrow-root-ca"])
    runcmd += [
        ["systemctl", "daemon-reload"],
        ["systemctl", "enable", STACK_UNIT_NAME],
    ]
    packages = ["docker.io", "docker-compose-v2"]
    if plan.agents == "full_machine":
        runcmd.append(["systemctl", "enable", *agents.FULL_MACHINE_UNITS])
        packages += agents.FULL_MACHINE_PACKAGES
    if plan.backup is not None:
        runcmd.append(["systemctl", "enable", "--now", BACKUP_TIMER_NAME])
    runcmd.append(["systemctl", "start", "--no-block", STACK_UNIT_NAME])
    doc = {
        "package_update": True,
        "packages": packages,
        "write_files": write_files,
        "runcmd": [_flow(cmd) for cmd in runcmd],
    }
    body = yaml_doc(
        doc,
        [
            HEADER.format(name=plan.name),
            "Carries secrets.env: keep this file mode 0600 and out of any repository.",
            "Target: Ubuntu 24.04 (noble) cloud image.",
        ],
    )
    return "#cloud-config\n" + body


def _flow(cmd):
    # A runcmd entry is an argv list; JSON arrays are valid YAML flow sequences.
    return Flow(json.dumps(cmd))


def _abs(rel):
    return rel if rel.startswith("/") else f"{INSTALL_ROOT}/{rel}"


def _ensure_newline(text):
    return text.rstrip("\n") + "\n"


def meta_data(plan):
    return f"instance-id: {plan.name}\nlocal-hostname: {plan.name}\n"


