"""Output layer for the ``single-host`` target: compose + Caddy + cloud-init.

Everything target-specific lives here: how a service becomes a compose
service, how routes become a Caddyfile, how TLS is terminated, how the files
reach a VM (cloud-init ``write_files``) and how the stack is started
(``burrow-stack.service``). The registry and ``render.plan`` know none of it.

A new target is a sibling module with a class exposing
``files(plan, secret_lines, customer_secrets, registry_auth) -> {path: (text, mode)}``,
registered in ``render.TARGETS``.

YAML is emitted by a small writer below (stdlib only). Scalars are written as
JSON strings, which are valid YAML double-quoted scalars, so no value can be
misread as a bool, number or null.
"""

import json
import os
import re

from . import agents, registry

HEADER = "Generated by burrow_install (ADR 0053) for install {name!r}. Do not edit; re-render."

INSTALL_ROOT = "/opt/burrow"
STACK_UNIT_NAME = agents.STACK_UNIT_NAME
# The pre-rename upgrade script (task 01a14dd8 stage 4). Every render writes it
# into the install as bin/burrow-migrate, byte for byte; on a fresh install its
# preflight refuses (there is no legacy root to move).
MIGRATE_SCRIPT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "migrate", "suite-to-burrow.sh"
)
SECRET_MODE = 0o600
FILE_MODE = 0o644
EXEC_MODE = 0o755

# ---------------------------------------------------------------------------
# Minimal YAML writer.
# ---------------------------------------------------------------------------

_PLAIN_KEY = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.-]*$")
_RESERVED = {"true", "false", "null", "yes", "no", "on", "off", "y", "n", "~"}


class Literal(str):
    """A multi-line string emitted as a YAML literal block (``|``)."""


class Flow(str):
    """Pre-rendered YAML flow text (a JSON array), emitted verbatim."""


def _key(key):
    if _PLAIN_KEY.match(key) and key.lower() not in _RESERVED:
        return key
    return json.dumps(key)


def _scalar(value):
    if isinstance(value, Flow):
        return str(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(value)


def _literal_lines(text, indent):
    if not text.endswith("\n") or text.endswith("\n\n"):
        raise ValueError("literal blocks must end with exactly one newline")
    if text[:1] in (" ", "\t"):
        raise ValueError("literal blocks must not start with whitespace")
    pad = "  " * indent
    return [pad + line if line else "" for line in text[:-1].split("\n")]


def yaml_lines(value, indent=0):
    pad = "  " * indent
    lines = []
    if isinstance(value, dict):
        for key, child in value.items():
            if isinstance(child, Literal):
                lines.append(f"{pad}{_key(key)}: |")
                lines.extend(_literal_lines(child, indent + 1))
            elif isinstance(child, dict | list):
                if not child:
                    lines.append(f"{pad}{_key(key)}: {'{}' if isinstance(child, dict) else '[]'}")
                else:
                    lines.append(f"{pad}{_key(key)}:")
                    lines.extend(yaml_lines(child, indent + 1))
            else:
                lines.append(f"{pad}{_key(key)}: {_scalar(child)}")
    elif isinstance(value, list):
        for item in value:
            if isinstance(item, dict):
                inner = yaml_lines(item, indent + 1)
                inner[0] = f"{pad}- " + inner[0][len(pad) + 2 :]
                lines.extend(inner)
            elif isinstance(item, list):
                raise TypeError("nested lists are not used")
            else:
                lines.append(f"{pad}- {_scalar(item)}")
    else:
        raise TypeError(f"unsupported YAML value {value!r}")
    return lines


def yaml_doc(value, comments=()):
    head = [f"# {c}" if c else "#" for c in comments]
    return "\n".join(head + yaml_lines(value)) + "\n"


