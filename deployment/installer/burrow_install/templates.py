def caddyfile(plan):
    lines = [f"# {HEADER.format(name=plan.name)}", "{"]
    if plan.tls == "acme":
        lines.append(f"\temail {plan.acme_email}")
    else:
        lines += [
            "\t# tls = internal: the root is generated on the host at first boot",
            "\t# (bin/burrow-root-ca) and never leaves it.",
            "\tskip_install_trust",
            "\tpki {",
            "\t\tca local {",
            f'\t\t\tname "{plan.name} internal CA"',
            "\t\t\troot {",
            "\t\t\t\tcert /etc/caddy/pki/root.crt",
            "\t\t\t\tkey /etc/caddy/pki/root.key",
            "\t\t\t}",
            "\t\t}",
            "\t}",
        ]
    lines.append("}")
    for host, port in plan.routes().items():
        container = next(s.container for s in plan.services.values() if host in s.routes)
        lines += ["", f"{host} {{"]
        if plan.tls == "internal":
            lines.append("\ttls internal")
        lines += [f"\treverse_proxy {container}:{port}", "}"]
    return "\n".join(lines) + "\n"


