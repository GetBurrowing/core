def secrets_env(plan, secret_lines, customer=False):
    lines = [f"# {HEADER.format(name=plan.name)}"]
    if customer:
        lines.append(
            "# SECRET, customer-supplied, read by no container yet (first-run bootstrap). Mode 0600."
        )
    else:
        lines.append(
            "# SECRET. Mode 0600. Never commit, never print. Feed back with --reuse-secrets."
        )
    lines += [f"{name}={value}" for name, value in secret_lines.items()]
    return "\n".join(lines) + "\n"


def models_json(plan):
    endpoints = [
        {k: e[k] for k in ("name", "kind", "base_url", "api_key_ref") if e[k] is not None}
        for e in plan.endpoints
    ]
    return json.dumps({"endpoints": endpoints}, indent=2, sort_keys=True) + "\n"


class SingleHost:
    name = "single-host"

    @staticmethod
    def files(plan, secret_lines, customer_secrets, registry_auth):
        """``secret_lines``: env consumed by containers, all in secrets.env.

        ``customer_secrets``: customer-supplied values no container reads yet;
        kept out of secrets.env (every env_file reader sees all of it).
        """
        install = {
            "compose.yaml": (compose(plan), FILE_MODE),
            "Caddyfile": (caddyfile(plan), FILE_MODE),
            "secrets.env": (secrets_env(plan, secret_lines), SECRET_MODE),
            "services.txt": ("\n".join(plan.containers) + "\n", FILE_MODE),
        }
        if customer_secrets:
            install["customer-secrets.env"] = (
                secrets_env(plan, customer_secrets, customer=True),
                SECRET_MODE,
            )
        for name, sql in sorted(plan.init_sql.items()):
            install[f"postgres-init/{name}"] = (sql, FILE_MODE)
        for rel, text in sorted(plan.config_files.items()):
            install[rel] = (text, FILE_MODE)
        for rel, value in sorted(plan.secret_file_values.items()):
            # A customer key mounted into ONE container (*_FILE), not secrets.env.
            install[rel] = (value, SECRET_MODE)
        for svc in plan.services.values():
            if svc.own_env_file and svc.secret_env():
                own = {k: secret_lines[k] for k in sorted(svc.secret_env())}
                install[own_env_file(svc)] = (secrets_env(plan, own), SECRET_MODE)
        if plan.endpoints:
            # Declared endpoints only. Nothing in core reads this yet; first-run
            # bootstrap (ADR 0053 follow-up 6) registers them.
            install["models.json"] = (models_json(plan), FILE_MODE)
        install.update(backup_files(plan))
        files = dict(install)
        host_env = None
        if plan.agents == "full_machine":
            host_env = agents.host_env(plan, secret_lines["AGENT_HOST_TOKEN"])
        files["user-data"] = (user_data(plan, install, registry_auth, host_env), SECRET_MODE)
        files["meta-data"] = (meta_data(plan), FILE_MODE)
        if registry_auth is not None:
            files["registry-auth.json"] = (_ensure_newline(registry_auth), SECRET_MODE)
        return files
