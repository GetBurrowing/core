def root_ca_script(plan):
    return f"""\
#!/bin/sh
# {HEADER.format(name=plan.name)}
# Creates this install's private root CA ON THIS HOST, once. The key never
# exists anywhere else. Caddy signs site certificates with it (Caddyfile pki).
set -eu
d={INSTALL_ROOT}/tls
[ -s "$d/root.crt" ] && exit 0
umask 077
mkdir -p "$d"
cat > "$d/root.cnf" <<'EOF'
[req]
distinguished_name = dn
x509_extensions = v3
prompt = no
[dn]
CN = {plan.name} internal root
[v3]
basicConstraints = critical,CA:TRUE
keyUsage = critical,keyCertSign,cRLSign
subjectKeyIdentifier = hash
EOF
openssl req -x509 -new -config "$d/root.cnf" -newkey ec -pkeyopt ec_paramgen_curve:P-256 \\
  -nodes -sha256 -days 3650 -keyout "$d/root.key" -out "$d/root.crt"
chmod 0600 "$d/root.key"
chmod 0644 "$d/root.crt"
"""


def ca_bundle_script(plan):
    pull = "never" if plan.images_preloaded else "missing"
    return f"""\
#!/bin/sh
# {HEADER.format(name=plan.name)}
# core-platform's trust store is CAStore's bundle (apps/platform/config/runtime.exs:3-10;
# Platform.OIDC.http_adapter/1 for sign-in), so it cannot verify this install's own
# root. Build CAStore's bundle from the
# core image + the install root, mounted read-only over the CAStore file.
# Retired by ADR 0053 follow-up 10 (a core env var for extra CA certs).
set -eu
image='{plan.core_image}'
castore='{registry.CASTORE_PATH}'
out={INSTALL_ROOT}/tls/ca-bundle.pem
if ! docker run --rm --pull {pull} --entrypoint cat "$image" "$castore" > "$out.tmp"; then
  echo "burrow-ca-bundle: cannot read $castore in $image; CAStore moved? see ADR 0053" >&2
  rm -f "$out.tmp"
  exit 1
fi
if ! grep -q 'BEGIN CERTIFICATE' "$out.tmp"; then
  echo "burrow-ca-bundle: $castore in $image holds no certificate" >&2
  rm -f "$out.tmp"
  exit 1
fi
printf '\\n' >> "$out.tmp"
cat {INSTALL_ROOT}/tls/root.crt >> "$out.tmp"
chmod 0644 "$out.tmp"
mv "$out.tmp" "$out"
"""


BACKUP_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "backup")
BACKUP_UNIT_NAME = "burrow-backup.service"
BACKUP_TIMER_NAME = "burrow-backup.timer"
# Pinned: the s3-compatible target uploads with this CLI image. A digest-pinned
# mirror of the upstream index (see .github/workflows/mirror-images.yml), never
# Docker Hub directly.
AWS_CLI_IMAGE = (
    "ghcr.io/getburrowing/aws-cli:2.17.62"
    "@sha256:183d4bb76169d35c12ba99e3384b605fee9a72fcb7ff1eeaa857fc27aa8fc713"
)
# Data volumes a backup snapshots when the install runs them.
BACKUP_VOLUMES = ("core-data", "agent-homes")


def _read_backup(name):
    with open(os.path.join(BACKUP_DIR, name), encoding="utf-8") as handle:
        return handle.read()


def backup_conf(plan):
    """``backup.conf``: KEY=value, names and refs only, never a secret value."""
    b = plan.backup
    svc_volumes = {v for svc in plan.services.values() for v in svc.volumes}
    volumes = [f"{plan.name}_{v}" for v in BACKUP_VOLUMES if v in svc_volumes]
    lines = [
        f"# {HEADER.format(name=plan.name)}",
        "# Read by bin/burrow-backup and bin/burrow-restore-drill. Secret REFS only.",
        f"TARGET={b['target']}",
        f"KEEP={b['keep']}",
        "PG_CONTAINER=core-postgres",
        f"PG_USER={registry.POSTGRES_USER}",
        f"HELPER_IMAGE={plan.services['core-postgres'].image}",
        f'VOLUMES="{" ".join(volumes)}"',
        f'HOST_DIRS="{"/home" if plan.agents == "full_machine" else ""}"',
        f"STATUS_VOLUME={plan.name}_core-data",
    ]
    if b["target"] == "local-path":
        lines.append(f"DEST_PATH={b['path']}")
    else:
        lines += [
            f"BUCKET={b['bucket']}",
            f"ENDPOINT={b['endpoint']}",
            f"REGION={b['region'] or ''}",
            f"ACCESS_KEY_REF={b['access_key_ref']}",
            f"SECRET_KEY_REF={b['secret_key_ref']}",
            f"AWS_CLI_IMAGE={AWS_CLI_IMAGE}",
        ]
    return "\n".join(lines) + "\n"


def backup_service_unit(plan):
    lines = [
        f"# {HEADER.format(name=plan.name)}",
        "[Unit]",
        f"Description=Burrow backup ({plan.name})",
        "Requires=docker.service",
        f"After=docker.service {STACK_UNIT_NAME}",
        "",
        "[Service]",
        "Type=oneshot",
        f"WorkingDirectory={INSTALL_ROOT}",
        f"Environment=BURROW_BACKUP_CONF={INSTALL_ROOT}/backup.conf",
    ]
    if plan.backup["target"] == "s3-compatible":
        # The refs' values, read by this unit only (mode 0600 root).
        lines.append(f"EnvironmentFile={INSTALL_ROOT}/customer-secrets.env")
    lines.append(f"ExecStart={INSTALL_ROOT}/bin/burrow-backup")
    return "\n".join(lines) + "\n"


def backup_timer_unit(plan):
    return (
        "\n".join(
            [
                f"# {HEADER.format(name=plan.name)}",
                "[Unit]",
                f"Description=Nightly Burrow backup ({plan.name})",
                "",
                "[Timer]",
                "OnCalendar=*-*-* 03:15:00",
                "RandomizedDelaySec=15m",
                "Persistent=true",
                f"Unit={BACKUP_UNIT_NAME}",
                "",
                "[Install]",
                "WantedBy=timers.target",
            ]
        )
        + "\n"
    )


def backup_files(plan):
    """Install files (relative to the install root) of the backup job, or {}."""
    if plan.backup is None:
        return {}
    return {
        "backup.conf": (backup_conf(plan), FILE_MODE),
        "bin/burrow-backup": (_read_backup("burrow-backup.sh"), EXEC_MODE),
        "bin/burrow-restore-drill": (_read_backup("burrow-restore-drill.sh"), EXEC_MODE),
    }


def stack_unit(plan):
    lines = [
        f"# {HEADER.format(name=plan.name)}",
        "[Unit]",
        f"Description=Burrow stack ({plan.name})",
        "Requires=docker.service",
        "After=docker.service network-online.target",
        "Wants=network-online.target",
    ]
    if plan.agents == "full_machine":
        # Starting the stack starts the agent host too (task 01a10322), also
        # when the operator starts it by hand after loading images.
        lines.append(f"Wants={agents.HOST_UNIT_NAME}")
    if plan.images_preloaded:
        # images.source = "preloaded": nothing pulls. The operator loads the
        # images, then touches this file and starts the unit.
        lines.append(f"ConditionPathExists={INSTALL_ROOT}/.images-loaded")
    lines += [
        "",
        "[Service]",
        "Type=oneshot",
        "RemainAfterExit=yes",
        f"WorkingDirectory={INSTALL_ROOT}",
    ]
    for rel in plan.host_files:
        lines.append(f"ExecStartPre=/usr/bin/test -s {INSTALL_ROOT}/{rel}")
    if plan.tls == "internal":
        lines.append(f"ExecStartPre={INSTALL_ROOT}/bin/burrow-ca-bundle")
    lines += [
        "ExecStart=/usr/bin/docker compose up -d --remove-orphans",
        "ExecStop=/usr/bin/docker compose down",
        "",
        "[Install]",
        "WantedBy=multi-user.target",
    ]
    return "\n".join(lines) + "\n"


