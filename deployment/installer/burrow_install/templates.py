def _caddy_mounts(plan):
    mounts = ["./Caddyfile:/etc/caddy/Caddyfile:ro"]
    if plan.tls == "internal":
        mounts += [
            "./tls/root.crt:/etc/caddy/pki/root.crt:ro",
            "./tls/root.key:/etc/caddy/pki/root.key:ro",
        ]
    return mounts


def _healthcheck(test):
    if test[:2] == ["CMD", "pg_isready"]:
        timing = {"interval": "10s", "timeout": "5s", "retries": 5}
    else:
        timing = {"interval": "30s", "timeout": "10s", "retries": 3, "start_period": "30s"}
    return {"test": list(test), **timing}


def _compose_service(plan, svc):
    out = {"container_name": svc.container, "image": svc.image}
    if svc.pull_never:
        out["pull_policy"] = "never"
    out["restart"] = "unless-stopped"
    if svc.command:
        out["command"] = list(svc.command)
    if svc.secret_env():
        # Secret-bearing env lines live only in secrets.env (mode 0600), or,
        # for a service that must not see the rest of it, in its own file.
        out["env_file"] = [own_env_file(svc) if svc.own_env_file else "secrets.env"]
    plain = svc.plain_env()
    if plain:
        out["environment"] = plain
    volumes = [f"{name}:{path}" for name, path in sorted(svc.volumes.items())]
    volumes += [
        f"{host if host.startswith('/') else './' + host}:{path}{':ro' if ro else ''}"
        for host, path, ro in sorted(svc.host_mounts)
    ]
    if svc.container == "caddy":
        volumes += _caddy_mounts(plan)
    if svc.systemd_init:
        volumes.append(agents.SYSTEMD_INIT_VOLUME)
    if volumes:
        out["volumes"] = volumes
    if svc.ports:
        out["ports"] = list(svc.ports)
    if svc.depends_on:
        out["depends_on"] = {d: {"condition": c} for d, c in svc.depends_on.items()}
    if svc.container == "caddy":
        # Every routed host resolves to Caddy INSIDE the stack too, so core
        # reaches its issuer (https://auth.<primary>) through the same TLS.
        out["networks"] = {"default": {"aliases": list(plan.routes())}}
    elif svc.networks:
        out["networks"] = {name: {} for name in svc.networks}
    if svc.systemd_init:
        out.update(agents.systemd_init_compose())
    if svc.healthcheck:
        out["healthcheck"] = _healthcheck(svc.healthcheck)
    if svc.gpu:
        out["deploy"] = {
            "resources": {
                "reservations": {
                    "devices": [{"driver": "nvidia", "count": "all", "capabilities": ["gpu"]}]
                }
            }
        }
    return out


def compose(plan):
    doc = {
        "name": plan.name,
        "services": {c: _compose_service(plan, plan.services[c]) for c in plan.containers},
    }
    volumes = sorted({v for svc in plan.services.values() for v in svc.volumes})
    if volumes:
        doc["volumes"] = {v: {} for v in volumes}
    networks = sorted({n for svc in plan.services.values() for n in svc.networks if n != "default"})
    if networks:
        doc["networks"] = {n: {} for n in networks}
    return yaml_doc(doc, [HEADER.format(name=plan.name)])


def own_env_file(svc):
    return f"{svc.container}.env"


