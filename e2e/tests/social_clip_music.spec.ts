/** Music selection/upload through the live human UI, with real CLI fixture outputs.
 * The fixture command file belongs to the isolated test process; no app route. */
import { test, expect, chromium } from "@playwright/test"
import { readFileSync, writeFileSync, existsSync, unlinkSync } from "node:fs"
const path = process.env.CLIP_MUSIC_FIXTURE
const fixture = path ? JSON.parse(readFileSync(path, "utf8")) : null

test("project audio upload, audition, gain, immutable preview, mute and safe failure", async ({}, info) => {
  test.skip(!fixture, "Seed private music fixture and set CLIP_MUSIC_FIXTURE")
  test.setTimeout(120_000)
  const browser = await chromium.connectOverCDP(process.env.CLIP_REVIEW_CDP ?? "http://127.0.0.1:9222")
  const context = await browser.newContext()
  await context.addCookies([{ name: "_platform_session", value: fixture.cookie, url: fixture.base_url }])
  const page = await context.newPage()
  try {
    await page.setViewportSize({ width: 1280, height: 650 })
    await page.goto(`${fixture.base_url}/m/social?tab=clips&view=review`)
    await page.waitForFunction(() => (window as any).liveSocket?.isConnected())
    await expect(page.locator('[data-role="music-empty"]')).toBeVisible()
    await page.locator('[data-role="music-upload"] input[type=file]').setInputFiles(process.env.CLIP_MUSIC_SONG!)
    await expect(page.locator('[data-role="music-preview"]')).toBeVisible()
    const song = await page.locator('#clip-music-song').inputValue()
    expect(song).toBeTruthy()
    const audio = page.locator('[data-role="music-preview"]')
    await audio.evaluate((a: HTMLAudioElement) => { a.load() })
    await expect.poll(() => audio.evaluate((a: HTMLAudioElement) => a.readyState)).toBeGreaterThan(0)
    await page.locator('#clip-music-gain').fill('-42')
    await expect(page.locator('[data-role="music-gain"]')).toContainText('-42')
    await expect(page.locator('[data-role="clip-approve"]')).toBeDisabled()
    const video = page.locator('[data-role="clip-player"] video')
    const before = await video.getAttribute('src')
    await page.screenshot({ path: info.outputPath('music-draft-desktop.jpg') })
    await page.locator('[data-role="caption-render"]').click()
    await expect(page.locator('[data-role="caption-pending"]')).toBeVisible()
    await expect(video).toHaveAttribute('src', before!)
    writeFileSync(path + '.command', JSON.stringify({ action: 'complete' }))
    await expect.poll(() => existsSync(path + '.receipt')).toBe(true)
    const receipt = JSON.parse(readFileSync(path + '.receipt', 'utf8')); unlinkSync(path + '.receipt')
    expect(receipt.payload.music).toEqual({file_id: song, enabled: true, level_db: -42})
    expect(receipt.payload.clip_overrides.mapped['audio.target_lufs']).toBeUndefined()
    await expect(page.locator('[data-role="music-applied"]')).toContainText('-42')
    await expect(video).not.toHaveAttribute('src', before!)
    await expect(page.locator('[data-role="clip-approve"]')).toBeEnabled()
    const footer = await page.locator('[data-role="clips-decide"]').boundingBox()
    expect(footer!.y + footer!.height).toBeLessThanOrEqual(650)
    await page.screenshot({ path: info.outputPath('music-applied-desktop.jpg') })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.locator('#clip-music-muted').selectOption('true')
    await expect(page.locator('#clip-music-gain')).toHaveValue('-42')
    await page.locator('#clip-music-muted').selectOption('false')
    await page.locator('#clip-music-gain').fill('-24')
    await expect(page.locator('[data-role="clips-pbar-approve"]')).toBeDisabled()
    const applied = await video.getAttribute('src')
    await page.locator('[data-role="caption-render"]').click()
    writeFileSync(path + '.command', JSON.stringify({ action: 'fail' }))
    await expect(page.locator('[data-role="caption-failure"]')).toBeVisible()
    await expect.poll(() => existsSync(path + '.receipt')).toBe(true)
    unlinkSync(path + '.receipt')
    await expect(video).toHaveAttribute('src', applied!)
    await expect(page.locator('[data-role="caption-render"]')).toBeEnabled()
    await expect(page.locator('[data-role="clips-pbar"]')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('music-failed-phone.jpg') })
    await page.locator('#clip-music-song').selectOption('')
    await expect(page.locator('[data-role="music-preview"]')).toHaveCount(0)
    await expect(page.locator('#clip-music-muted')).toBeDisabled()
  } finally { await context.close(); await browser.close() }
})
