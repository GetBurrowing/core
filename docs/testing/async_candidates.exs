# Classifies every non-async test file under apps/platform/test by the
# signals that make it unsafe to run `async: true` (task 01a17ac3, stage 2).
#
#     elixir docs/testing/async_candidates.exs > docs/testing/async-classification.md
#
# Run from the repository root. Read-only: it only reads files.
#
# Every signal is a regex over the test file's text (plus, for
# compile_env, the lib modules that call Application.compile_env), so a hit
# is a reason to look, not proof, and "no signal" is an UPPER bound on what
# could be converted: a file can still depend on shared-sandbox draining or
# on a global it reaches through a helper this grep does not open.

root = File.cwd!()
platform = Path.join(root, "apps/platform")

unless File.dir?(Path.join(platform, "test")) do
  IO.puts(:stderr, "run from the repository root (apps/platform/test not found)")
  System.halt(1)
end

rel = &Path.relative_to(&1, platform)

compile_env_modules =
  Path.wildcard(Path.join(platform, "lib/**/*.ex"))
  |> Enum.filter(&(File.read!(&1) =~ "Application.compile_env"))
  |> Enum.flat_map(fn path ->
    Regex.scan(~r/^\s*defmodule\s+([A-Z][\w.]*)/m, File.read!(path), capture: :all_but_first)
    |> List.flatten()
  end)

singletons =
  ~w(AttentionRouter TaskRouter TaskRouterSupervisor TaskRouterWatcher
     SystemEventScheduler HeartbeatScheduler)

signals = [
  {"app_env", ~r/Application\.(put_env|delete_env|put_all_env)\b/},
  {"system_env", ~r/System\.(put_env|delete_env)\b/},
  {"persistent_term", ~r/:persistent_term\./},
  {"mox_global", ~r/set_mox_global|set_mox_from_context/},
  {"telemetry_attach", ~r/:telemetry\.attach/},
  {"sandbox_mode", ~r/Sandbox\.mode|shared:\s*true/},
  {"named_process",
   ~r/Process\.register|:global\.|Registry\.register|\bname:\s*(__MODULE__|[A-Z][\w.]*\b(?!\.\w+\()|:[a-z_]\w*)/},
  {"named_ets", ~r/:ets\.new\([^)]*named_table|:ets\.\w+\(\s*(:[a-z_]\w*|[A-Z][\w.]*)\s*,/},
  {"pubsub_subscribe", ~r/PubSub\.subscribe|Endpoint\.subscribe|\bsubscribe\(/},
  {"logger_configure", ~r/Logger\.(configure|put_module_level|put_application_level)/},
  {"oban_quantum", ~r/\bOban\b|\bQuantum\b/},
  {"isolated_beam", ~r/@moduletag\s+:isolated_beam/},
  {"compile_env_module",
   case compile_env_modules do
     [] -> ~r/a\A(?!a)/
     mods -> Regex.compile!("\\b(" <> Enum.map_join(mods, "|", &Regex.escape/1) <> ")\\b")
   end},
  {"repo_singleton", Regex.compile!("\\b(" <> Enum.join(singletons, "|") <> ")\\b")}
]

files = Path.wildcard(Path.join(platform, "test/**/*_test.exs")) |> Enum.sort()

# Read the option off the file's first `use <...>Case` line only: 75 files
# that are `async: false` also mention `async: true` in a comment or string.
async_of = fn src ->
  opts =
    case Regex.run(~r/^\s*use\s+[A-Z][\w.]*Case\b(.*)$/m, src, capture: :all_but_first) do
      [rest] -> rest
      nil -> ""
    end

  cond do
    opts =~ ~r/async:\s*true/ -> :async
    opts =~ ~r/async:\s*false/ -> :serial
    true -> :default
  end
end

# Bindings are not filters here on purpose: inside `for`, `mode = ...` would
# be one, and would drop every row whose value is falsy.
rows =
  files
  |> Enum.map(fn path ->
    src = File.read!(path)
    {rel.(path), async_of.(src), for({name, re} <- signals, Regex.match?(re, src), do: name)}
  end)
  |> Enum.reject(fn {_, mode, _} -> mode == :async end)

disq = Enum.filter(rows, fn {_, _, hits} -> hits != [] end)
cand = Enum.filter(rows, fn {_, _, hits} -> hits == [] end)

counts =
  for {name, _} <- signals,
      do: {name, Enum.count(rows, fn {_, _, hits} -> name in hits end)}

only =
  for {name, _} <- signals,
      do: {name, Enum.count(rows, fn {_, _, hits} -> hits == [name] end)}

mode_label = fn
  :serial -> "async: false"
  :default -> "no option (default false)"
end

out = [
  "# async classification (task 01a17ac3, stage 2)\n\n",
  "Generated by `elixir docs/testing/async_candidates.exs` from the repository root. ",
  "Do not hand-edit; re-run the script.\n\n",
  "Stage 2 was re-scoped to correctness (the ticket's falsifier held: sharded hosted ",
  "`Test` took 7m29s, under 10 min), so this is an inventory of WHY each serial file is ",
  "serial. No file was flipped to `async: true` from it.\n\n",
  "Each signal is a regex hit in the test file's own text, so a hit is a reason to look, ",
  "not proof. A file with no signal is a candidate, not a safe conversion: it can still ",
  "rely on the shared sandbox and singleton draining that non-async DataCase/ConnCase ",
  "gets (`data_case.ex`: `shared: not tags[:async]`, settle_singletons, ",
  "stop_task_routers_or_warn) through a helper this grep does not open. Treat the ",
  "candidate count as an upper bound.\n\n",
  "A file's mode is read from its first `use <...>Case` line. The planner's 1,206 ",
  "non-async files (at `f46ed3f2a`) came from a whole-file `grep -l 'async: false'`, ",
  "which also counts `async: true` files that mention `async: false` in a comment.\n\n",
  "## Counts\n\n",
  "- test files: #{length(files)}\n",
  "- non-async: #{length(rows)} (#{Enum.count(rows, &(elem(&1, 1) == :serial))} `async: false`, ",
  "#{Enum.count(rows, &(elem(&1, 1) == :default))} with no option)\n",
  "- disqualified (at least one signal): #{length(disq)}\n",
  "- candidates (no signal): #{length(cand)}\n\n",
  "| signal | files hitting it | files where it is the only signal |\n|---|---|---|\n",
  for({{name, n}, {_, o}} <- Enum.zip(counts, only), do: "| `#{name}` | #{n} | #{o} |\n"),
  "\n`compile_env_module` matches test files naming a lib module that calls ",
  "`Application.compile_env`: #{Enum.map_join(compile_env_modules, ", ", &"`#{&1}`")}. ",
  "`repo_singleton` matches #{Enum.map_join(singletons, ", ", &"`#{&1}`")}.\n\n",
  "## Disqualified\n\n| file | async | signals |\n|---|---|---|\n",
  for({f, m, hits} <- disq, do: "| `#{f}` | #{mode_label.(m)} | #{Enum.join(hits, ", ")} |\n"),
  "\n## Candidates (no signal; upper bound)\n\n| file | async |\n|---|---|\n",
  for({f, m, _} <- cand, do: "| `#{f}` | #{mode_label.(m)} |\n")
]

IO.write(out)
