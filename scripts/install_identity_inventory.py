def classify(path: str) -> str:
    if path in A_DEP_FILES or path.startswith("clients/"):
        return "a-dep"
    if any(path.startswith(p) for p in HISTORY_PREFIXES) or "CHANGELOG" in path:
        return "c"
    if path == "apps/platform/config/test.exs":
        return "b"
    parts = path.split("/")
    if "test" in parts or "tests" in parts or path.startswith("e2e/"):
        return "b"
    return "a"


def disposition(path: str, cls: str, data: bytes) -> str:
    if path in ON_PURPOSE_FIXTURES:
        return ON_PURPOSE_FIXTURES[path]
    if path in A_DEP_FILES:
        return A_DEP_FILES[path]
    if cls == "a-dep":
        other = len(TOKEN.findall(APP_ID.sub(b"", data)))
        if other == 0:
            return "mobile app: published bundle/package id only. Keep; out of guard scope."
        ids = len(APP_ID.findall(data))
        return (
            f"mobile app: {ids} bundle/package-id hit(s) and {other} other hit(s) "
            "(e.g. a `suite.example.com` host default). Out of guard scope; FOLLOW-UP."
        )
    if cls == "c":
        return "history (already-run migration / eval cassette / ADR / audit). Keep."
    if cls == "b":
        if path.startswith("apps/platform/test/") or path.startswith("apps/game_stream/test/"):
            return "UNEXPECTED: stage 4 renamed the mechanical test fixtures to acme; an unlisted hit here is unclassified."
        return "test fixture outside the apps' test trees (stage 4 scope). FOLLOW-UP."
    # class (a)
    if path == "apps/platform/lib/platform/tasks.ex":
        return "stage 3 (`@scope_keys` / `\"fabrikam\"` bucket); stage 2 removed the comments."
    if path == "apps/platform/lib/platform/tenancy.ex":
        return "stage 3 (`:fabrikam` entries in `@scope_classes` / `@scope_labels`, with scope_pill's `:fabrikam` scope); stage 2 removed the rest."
    if path.startswith("apps/platform/lib/platform_web/") or path.startswith("apps/platform/assets/"):
        return "stage 3 (web copy, assigns, CSS)."
    if path.startswith("apps/platform/lib/") or path.startswith("services/"):
        return "UNEXPECTED: stage 2 removed every backend hit; a hit here is a regression."
    if path in ("apps/platform/config/config.exs", "apps/platform/config/dev.exs", "apps/platform/config/runtime.exs"):
        return "UNEXPECTED: stage 2 removed every config hit; a hit here is a regression."
    if path == "deployment/schema/install-modules.md":
        return "names Rowan's production installs. NO plan stage removes it yet; allowlisted pending a decision."
    return "product doc / CI comment outside the guard's scanned set. FOLLOW-UP; no plan stage removes it."


# --- measurement ------------------------------------------------------------


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


# This inventory's own tooling must name the token; it is listed, not counted.
SELF = [
    "scripts/install_identity_inventory.py",
    "docs/architecture/install-identity-inventory.md",
    "apps/platform/test/platform/regression/no_fabrikam_identity_guard_test.exs",
]


def measure():
    rows = []
    for line in git("grep", "-ic", "fabrikam").splitlines():
        path, _, n = line.rpartition(":")
        if path in SELF:
            continue
        data = (ROOT / path).read_bytes()
        cls = classify(path)
        rows.append(
            {
                "path": path,
                "lines": int(n),
                "matches": len(TOKEN.findall(data)),
                "class": cls,
                "guard": in_guard_scope(path),
                "disposition": disposition(path, cls, data),
            }
        )
    return sorted(rows, key=lambda r: r["path"])


def sibling_hits():
    out = []
    for line in git("grep", "-nIwE", "soylent|wayne_tech|wayne-tech|cyberdyne|paragon", "--", "apps/*/lib/*").splitlines():
        path, lineno, _ = line.split(":", 2)
        out.append((path, int(lineno)))
    by_file = defaultdict(list)
    for path, lineno in out:
        by_file[path].append(lineno)
    return by_file


