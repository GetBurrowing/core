def _scanned() -> set[str]:
    found = set()
    for g in SCAN_GLOBS:
        for f in ROOT.glob(g):
            if f.is_file():
                found.add(f.relative_to(ROOT).as_posix())
    return {
        p
        for p in found
        if not any(p.startswith(x) for x in SCAN_EXCLUDE_PREFIXES)
        and "/__pycache__/" not in p
        and "/node_modules/" not in p
        and not any(part.startswith(".") for part in p.split("/"))
    }


SCANNED = None


def in_guard_scope(path: str) -> bool:
    global SCANNED
    if SCANNED is None:
        SCANNED = _scanned()
    return path in SCANNED


