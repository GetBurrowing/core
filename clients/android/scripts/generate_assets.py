#!/usr/bin/env python3
"""Generate the Burrow Android icon, splash and status-bar vector drawables.

Source: the Burrow arch on main (PR #1191, merged as e9b9b627), read from
clients/ios/ios/App/App/Assets.xcassets/AppIcon.appiconset/:

- AppIcon-1024-tinted.png is the arch's alpha mask. Its outline is traced
  row by row into a polygon (every point lies on the mask's 50% edge),
  simplified with Ramer-Douglas-Peucker at 0.6 px of 1024, and emitted as
  one vector path, so every drawable here shares the exact same geometry.
- AppIcon-1024.png gives the colours: the gradient field (sampled at the
  bottom-left, centre and top-right) and the cream arch.

Sizes are the Android canvas's (01a10d91, "Adaptive icon from the Burrow
arch"): foreground arch 56dp wide in the 108dp tile (inside the 66dp safe
zone), splash arch ~96dp, status-bar arch 20dp wide in 24dp.

    python3 clients/android/scripts/generate_assets.py
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
IOS_ICONS = ROOT.parent / "ios" / "ios" / "App" / "App" / "Assets.xcassets" / "AppIcon.appiconset"
RES = ROOT / "android" / "app" / "src" / "main" / "res"

STEP = 2          # rows between samples on the 1024 mask
TOLERANCE = 0.6   # RDP tolerance, in 1024-mask pixels


def hexc(rgb):
    return "#FF%02X%02X%02X" % rgb


def runs(row, width, threshold=128):
    out, start = [], None
    for x in range(width):
        on = row[x] >= threshold
        if on and start is None:
            start = x
        elif not on and start is not None:
            out.append((start, x))
            start = None
    if start is not None:
        out.append((start, width))
    return out


def trace(mask):
    """The arch outline as one polygon, from the bottom-left foot round the
    outside to the bottom-right foot, then up and round the opening."""
    w, h = mask.size
    px = mask.load()
    rows = {}
    for y in range(h):
        r = runs([px[x, y] for x in range(w)], w)
        if r:
            rows[y] = r
    top, bottom = min(rows), max(rows)
    ys = list(range(top, bottom + 1, STEP))
    if ys[-1] != bottom:
        ys.append(bottom)
    mid = None
    outer_left, outer_right, inner_left, inner_right = [], [], [], []
    for y in ys:
        r = rows[y]
        if len(r) >= 2:
            outer_left.append((r[0][0], y))
            inner_left.append((r[0][1], y))
            inner_right.append((r[-1][0], y))
            outer_right.append((r[-1][1], y))
            mid = (r[0][1] + r[-1][0]) / 2
        elif mid is None:
            # Above the opening: one run spans the arch.
            outer_left.append((r[0][0], y))
            outer_right.append((r[0][1], y))
        elif (r[0][0] + r[0][1]) / 2 < mid:
            # Below where the other foot ended: the left foot only.
            outer_left.append((r[0][0], y))
            inner_left.append((r[0][1], y))
        else:
            inner_right.append((r[0][0], y))
            outer_right.append((r[0][1], y))
    return list(reversed(outer_left)) + outer_right + list(reversed(inner_right)) + inner_left


def rdp(points, eps):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = (dx * dx + dy * dy) ** 0.5 or 1.0
    best, index = 0.0, 0
    for i in range(1, len(points) - 1):
        x0, y0 = points[i]
        d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / norm
        if d > best:
            best, index = d, i
    if best > eps:
        return rdp(points[: index + 1], eps)[:-1] + rdp(points[index:], eps)
    return [points[0], points[-1]]


def path_data(poly, box, width_dp, canvas_dp, offset_y=0.0):
    """Scale the polygon so the arch is width_dp wide, centred on canvas_dp."""
    x0, y0, x1, y1 = box
    scale = width_dp / (x1 - x0)
    height_dp = (y1 - y0) * scale
    ox = (canvas_dp - width_dp) / 2
    oy = (canvas_dp - height_dp) / 2 + offset_y
    pts = [((x - x0) * scale + ox, (y - y0) * scale + oy) for x, y in poly]
    head = "M%.2f,%.2f" % pts[0]
    body = "".join("L%.2f,%.2f" % p for p in pts[1:])
    return head + body + "Z", height_dp


HEADER = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by clients/android/scripts/generate_assets.py; do not edit. -->\n"


def vector(size_dp, body, viewport=None, tint=None, ignore=None):
    v = viewport or size_dp
    tint_attr = f'\n    android:tint="{tint}"' if tint else ""
    ignore_attr = (
        '    xmlns:tools="http://schemas.android.com/tools"\n'
        + f'    tools:ignore="{ignore}"\n'
    ) if ignore else ""
    return (
        HEADER
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        + '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        + ignore_attr
        + f'    android:width="{size_dp}dp"\n    android:height="{size_dp}dp"\n'
        + f'    android:viewportWidth="{v}"\n    android:viewportHeight="{v}"{tint_attr}>\n'
        + body
        + "</vector>\n"
    )


def gradient_fill(start, center, end, x0, y0, x1, y1):
    return (
        '        <aapt:attr name="android:fillColor">\n'
        + f'            <gradient android:type="linear" android:startX="{x0}" android:startY="{y0}"\n'
        + f'                android:endX="{x1}" android:endY="{y1}"\n'
        + f'                android:startColor="{start}" android:centerColor="{center}" android:endColor="{end}" />\n'
        + "        </aapt:attr>\n"
    )


def write(rel, text):
    path = RES / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main():
    mask = Image.open(IOS_ICONS / "AppIcon-1024-tinted.png").convert("L")
    colour = Image.open(IOS_ICONS / "AppIcon-1024.png").convert("RGB")
    box = mask.point(lambda v: 255 if v >= 128 else 0).getbbox()
    poly = rdp(trace(mask), TOLERANCE)

    start = hexc(colour.getpixel((4, 1019)))   # orange-red, bottom left
    center = hexc(colour.getpixel((512, 512)))
    end = hexc(colour.getpixel((1019, 4)))     # amber, top right
    cream = hexc(colour.getpixel((600, 350)))  # inside the arch

    # Adaptive icon background: the gradient field, full bleed on 108dp.
    write("drawable/ic_launcher_background.xml", vector(108, (
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        + gradient_fill(start, center, end, 0, 108, 108, 0)
        + "    </path>\n")))

    # Foreground and monochrome: the arch 56dp wide, centred in 108dp.
    fg, fg_h = path_data(poly, box, 56, 108)
    write("drawable/ic_launcher_foreground.xml", vector(108,
        f'    <path android:fillColor="{cream}" android:pathData="{fg}" />\n'))
    write("drawable/ic_launcher_monochrome.xml", vector(108,
        f'    <path android:fillColor="#FF000000" android:pathData="{fg}" />\n'))

    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )
    write("mipmap-anydpi/ic_launcher.xml", adaptive)
    write("mipmap-anydpi/ic_launcher_round.xml", adaptive)

    # Splash (SplashScreen API, icon without background): 288dp canvas whose
    # visible area is the centred 192dp circle; the arch ~96dp wide in its
    # orange gradient on the base-100 field (no cyan).
    sp, sp_h = path_data(poly, box, 96, 288)
    # 288dp is the SplashScreen API's icon canvas, over lint's 200dp hint.
    write("drawable/splash_arch.xml", vector(288, (
        f'    <path android:pathData="{sp}">\n'
        + gradient_fill(start, center, end, 96, 144 + sp_h / 2, 192, 144 - sp_h / 2)
        + "    </path>\n"), ignore="VectorRaster"))

    # Status-bar small icon: white arch 20dp wide on 24dp, system-tinted.
    sb, sb_h = path_data(poly, box, 20, 24)
    # Used by the notifications in stage 3.
    write("drawable/ic_stat_burrow.xml", vector(24,
        f'    <path android:fillColor="#FFFFFFFF" android:pathData="{sb}" />\n', ignore="UnusedResources"))

    # The opening at the feet, in dp at status-bar size (canvas: >= 4dp).
    # Narrowest the opening gets is at its feet: inner-right minus inner-left
    # on the lowest row both feet share.
    w = box[2] - box[0]
    px = mask.load()
    shared = max(y for y in range(box[1], box[3]) if len(runs([px[x, y] for x in range(mask.size[0])], mask.size[0])) >= 2)
    r = runs([px[x, shared] for x in range(mask.size[0])], mask.size[0])
    opening = (r[-1][0] - r[0][1]) * 20 / w
    print(f"points={len(poly)} fg={56}x{fg_h:.1f}dp splash=96x{sp_h:.1f}dp "
          f"statusbar=20x{sb_h:.1f}dp opening={opening:.1f}dp "
          f"colours start={start} center={center} end={end} arch={cream}")


if __name__ == "__main__":
    main()
