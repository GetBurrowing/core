defmodule PlatformWeb.ChatLiveSpokenOrderTest do
  @moduledoc """
  Task 01a07401 stage 2 — the scrollback ORDERS by the stamp stage 1 writes.

  Stage 1 put `metadata["spoken_at"]` (the dispatch instant) on an agent's
  spoken line, because that row's `inserted_at` is stamped when the runtime's
  ack comes back, which can be seconds or minutes later. Stage 1 proved the
  stamp is written and is not a copy of insertion time. It did not make
  anything read it: the room still rendered by `inserted_at`, so the fix was
  invisible. This file is the read side.

  ## What each case is worth

  `renders in its spoken position` is the anti-vacuity case, and it is
  deliberately NOT written as "the stamp is earlier than the insert time".
  Stage 1 reported that a bare `DateTime.compare(spoken_at, inserted_at) ==
  :lt` passes even when the stamp is a fresh `utc_now/0` read taken at post
  time — i.e. on the exact defect — because that read still lands ~1.4 ms
  ahead of the row's autogenerated `inserted_at`. A comparison that a
  millisecond of clock jitter can satisfy is measuring jitter. So the skew
  here is 30 SECONDS, seeded explicitly rather than slept for, and what is
  asserted is the agent line's POSITION relative to the two human messages
  that were said while its ack was in flight. Reverting
  `Platform.Chat.list_messages/2` to `order_by: inserted_at` puts the agent
  line last and fails it.

  `keeps its own place between two unstamped rows` and `a room with no stamps
  renders unchanged` are the compatibility half, and they are the half a
  backfill cannot rescue: no backfill is possible here (nothing ever recorded
  the dispatch instant of a historical utterance), so every message this
  product wrote before stage 1 has a NULL stamp forever. `coalesce` must land
  those rows at their own `inserted_at` — not hoisted to the top of the room
  and not dumped at the bottom of it — and a test written only against
  freshly-created stamped rows would never notice either failure.

  `paging` guards what changing the sort key costs the keyset cursor. `id` is
  UUIDv7 and agrees with insertion order, which is exactly what the ordering
  key no longer does; with an `id`-only cursor a page boundary landing inside
  a late-acked line's displacement re-serves rows the reader has already seen.
  The case pages a room the whole way down and asserts the concatenation is
  the single-shot ordering exactly — no repeats, nothing skipped.

  `async: false` matches the sibling ChatLive suites.
  """

  use PlatformWeb.ConnCase, async: false
  import Phoenix.LiveViewTest

  alias Platform.Accounts.User
  alias Platform.Agents.Agent
  alias Platform.Chat
  alias Platform.Repo

  # Seeded skew between dispatch and ack. Three orders of magnitude past
  # anything clock jitter can produce, and past the 15 s rendezvous, so it is
  # unambiguously in `SayRegistry`'s five-minute back-fill territory.
  @ack_skew_seconds 30

  setup %{conn: conn} do
    n = System.unique_integer([:positive])

    user =
      Repo.insert!(%User{
        email: "spoken_order_#{n}@example.com",
        name: "Spoken Order Tester",
        oidc_sub: "oidc-spoken-order-#{n}"
      })

    {:ok, space} =
      Chat.create_space(%{
        name: "Spoken Order #{n}",
        slug: "spoken-order-#{n}",
        kind: "channel"
      })

    # A real meeting room over this space: the meeting chat surface IS this
    # space (see `Platform.Meetings.post_spoken_utterance/2`, which posts the
    # spoken line into `room.space_id`), so the surface under test is the one
    # ChatLive renders.
    {:ok, room} = Platform.Meetings.ensure_room(space.id)
    {:ok, room} = Platform.Meetings.activate_room(room)

    agent =
      Repo.insert!(%Agent{
        slug: "spoken-order-agent-#{n}",
        name: "Spoken Order Agent #{n}",
        status: "active"
      })

    {:ok, agent_participant} = Chat.add_agent_participant(space.id, agent)
    human = add_human(space, "human")

    {:ok,
     conn: init_test_session(conn, current_user_id: user.id),
     space: space,
     room: room,
     human: human,
     agent_participant: agent_participant}
  end

  defp add_human(space, label) do
    n = System.unique_integer([:positive])

    {:ok, participant} =
      Chat.add_participant(space.id, %{
        participant_type: "user",
        participant_id: Ecto.UUID.generate(),
        display_name: "#{label}-#{n}",
        joined_at: DateTime.utc_now()
      })

    participant
  end

  # Post a message and then force its `inserted_at`, which is otherwise
  # autogenerated. Posting order therefore fixes the UUIDv7 `id` order (what
  # the room used to sort by) while `inserted_at` and `spoken_at` are set
  # independently — which is the whole point: the defect only shows when
  # those two disagree.
  defp post_at(space, participant, content, inserted_at, metadata \\ %{}) do
    {:ok, msg} =
      Chat.post_message(%{
        space_id: space.id,
        participant_id: participant.id,
        content_type: "text",
        content: content,
        metadata: metadata
      })

    msg
    |> Ecto.Changeset.change(inserted_at: inserted_at)
    |> Repo.update!()
  end

  # The metadata shape `post_spoken_utterance/2` actually writes (stage 1).
  defp say_metadata(room, spoken_at) do
    %{
      "source" => "meetings.say",
      "utterance_id" => Ecto.UUID.generate(),
      "room_name" => room.livekit_room_name,
      "spoken_at" => DateTime.to_iso8601(spoken_at),
      "spoken_at_source" => "dispatch"
    }
  end

  defp base_time do
    DateTime.utc_now() |> DateTime.add(-3600, :second) |> DateTime.truncate(:microsecond)
  end

  # Message ids in the order the message list actually renders them.
  # `LazyHTML.query/2` descends the whole tree; `filter/2` matches only a
  # fragment's root nodes and would return `[]` for a nested row.
  defp rendered_message_order(html) do
    html
    |> LazyHTML.from_fragment()
    |> LazyHTML.query("[data-message-id]")
    |> LazyHTML.attribute("data-message-id")
    |> Enum.uniq()
  end

  defp index_of(order, id), do: Enum.find_index(order, &(&1 == id))

  describe "an agent line whose ack came back late" do
    test "renders in its spoken position, before the humans who spoke after it",
         %{conn: conn, space: space, room: room, human: human, agent_participant: agent} do
      t = base_time()

      # The two humans are posted FIRST, so their ids are the low ones and
      # `inserted_at` order and `id` order agree for them.
      human_a = post_at(space, human, "human at T+5", DateTime.add(t, 5, :second))
      human_b = post_at(space, human, "human at T+10", DateTime.add(t, 10, :second))

      # The agent's line was dispatched at T — before either human spoke —
      # but its ack came back at T+30, so the row is written last and carries
      # the LARGEST id and the LATEST `inserted_at` in the room.
      agent_line =
        post_at(
          space,
          agent,
          "agent said this at T",
          DateTime.add(t, @ack_skew_seconds, :second),
          say_metadata(room, t)
        )

      {:ok, view, _html} = live(conn, "/chat/#{space.slug}")
      order = rendered_message_order(render(view))

      # Positive control: all three rows are actually on screen, so the
      # position assertions below cannot pass by absence.
      assert index_of(order, agent_line.id)
      assert index_of(order, human_a.id)
      assert index_of(order, human_b.id)

      assert index_of(order, agent_line.id) < index_of(order, human_a.id),
             "the agent line must render before the human who spoke 5s after it"

      assert index_of(order, agent_line.id) < index_of(order, human_b.id),
             "the agent line must render before the human who spoke 10s after it"

      # And the humans keep their own relative order, so this is a move of
      # one row and not a wholesale reversal.
      assert index_of(order, human_a.id) < index_of(order, human_b.id)
    end

    test "the row's own clock shows when it was spoken, not when it was acked",
         %{conn: conn, space: space, room: room, agent_participant: agent} do
      t = base_time()

      agent_line =
        post_at(
          space,
          agent,
          "agent said this at T",
          DateTime.add(t, @ack_skew_seconds, :second),
          say_metadata(room, t)
        )

      {:ok, view, _html} = live(conn, "/chat/#{space.slug}")

      stamp =
        view
        |> render()
        |> LazyHTML.from_fragment()
        |> LazyHTML.query(~s([id="message-time-#{agent_line.id}"]))
        |> LazyHTML.attribute("datetime")

      assert stamp == [DateTime.to_iso8601(t)],
             "a row moved into its spoken position while printing its ack time " <>
               "reads as a scrollback that is merely out of order"
    end
  end

  describe "messages with no stamp (everything written before this shipped)" do
    test "keep their own place between stamped rows, neither hoisted nor sunk",
         %{conn: conn, space: space, room: room, human: human, agent_participant: agent} do
      t = base_time()

      older = post_at(space, human, "unstamped, older", DateTime.add(t, 10, :second))
      newer = post_at(space, human, "unstamped, newer", DateTime.add(t, 50, :second))

      # Spoken at T+20 — between the two unstamped rows — acked at T+80,
      # after both of them.
      agent_line =
        post_at(
          space,
          agent,
          "agent said this at T+20",
          DateTime.add(t, 80, :second),
          say_metadata(room, DateTime.add(t, 20, :second))
        )

      {:ok, view, _html} = live(conn, "/chat/#{space.slug}")
      order = rendered_message_order(render(view))

      assert [older.id, agent_line.id, newer.id] ==
               Enum.filter(order, &(&1 in [older.id, agent_line.id, newer.id])),
             "a NULL stamp must fall back to the row's own inserted_at, so an " <>
               "unstamped row sorts at its own place and not at an end of the room"
    end

    test "a room with no stamps at all renders in exactly the order it always did",
         %{conn: conn, space: space, human: human} do
      t = base_time()

      seeded =
        for i <- 1..8 do
          post_at(space, human, "historical #{i}", DateTime.add(t, i * 7, :second))
        end

      {:ok, view, _html} = live(conn, "/chat/#{space.slug}")
      order = rendered_message_order(render(view))

      assert Enum.map(seeded, & &1.id) == order
    end
  end

  describe "keyset paging over a reordered room" do
    test "pages the whole room without repeating or skipping a row",
         %{space: space, room: room, human: human, agent_participant: agent} do
      t = base_time()

      # 40 rows, with a late-acked agent line in every seventh slot: spoken
      # at its own slot, acked 90 s (nine slots) later. They are POSTED in
      # ack order, because that is when the row is actually written — which
      # is what makes `id` (UUIDv7, minted at write) disagree with the order
      # the room renders in. Seeding them in spoken order instead would make
      # `id` agree with the sort key and the case would prove nothing: it
      # was written that way first and stayed green under an id-only cursor.
      # Page size is 9, so boundaries land inside those displacements
      # repeatedly.
      events =
        for i <- 1..40 do
          spoken = DateTime.add(t, i * 10, :second)

          if rem(i, 7) == 0 do
            %{
              spoken: spoken,
              inserted: DateTime.add(spoken, 90, :second),
              author: agent,
              content: "agent #{i}",
              metadata: say_metadata(room, spoken)
            }
          else
            %{
              spoken: spoken,
              inserted: spoken,
              author: human,
              content: "human #{i}",
              metadata: %{}
            }
          end
        end

      events
      |> Enum.sort_by(& &1.inserted, DateTime)
      |> Enum.each(&post_at(space, &1.author, &1.content, &1.inserted, &1.metadata))

      single_shot =
        space.id
        |> Chat.list_messages(limit: 500, top_level_only: true)
        |> Enum.map(& &1.id)

      assert length(single_shot) == 40

      paged = page_all(space.id, nil, [])

      assert paged == single_shot,
             "paging with a keyset cursor must reproduce the single-shot order"

      assert length(Enum.uniq(paged)) == length(paged), "a row was served twice"
    end
  end

  # Walk `list_messages/2` backwards page by page, newest first, exactly the
  # way `MessagesHooks.load_older_messages/2` does: the cursor is the id of
  # the OLDEST row of the batch by the render order, which under an id-only
  # keyset is not the smallest id in the batch.
  defp page_all(space_id, cursor, acc) do
    opts = [limit: 9, top_level_only: true]
    opts = if cursor, do: Keyword.put(opts, :before_id, cursor), else: opts

    case Chat.list_messages(space_id, opts) do
      [] ->
        acc

      page ->
        ids = Enum.map(page, & &1.id)
        # `list_messages/2` returns DESC; the last element is the oldest.
        page_all(space_id, List.last(ids), acc ++ ids)
    end
  end

  describe "Chat.message_ordered_at/1" do
    test "falls back to inserted_at for a missing, empty or malformed stamp" do
      now = DateTime.utc_now()

      for metadata <- [
            %{},
            %{"spoken_at" => nil},
            %{"spoken_at" => ""},
            %{"spoken_at" => "not a timestamp"},
            %{"spoken_at" => 12_345}
          ] do
        assert Chat.message_ordered_at(%{metadata: metadata, inserted_at: now}) == now,
               "malformed metadata must not change where a row sorts: #{inspect(metadata)}"
      end
    end

    test "reads a well-formed stamp" do
      now = DateTime.utc_now()
      spoken = DateTime.add(now, -30, :second)

      assert Chat.message_ordered_at(%{
               metadata: %{"spoken_at" => DateTime.to_iso8601(spoken)},
               inserted_at: now
             }) == spoken
    end
  end
end
