defmodule PlatformWeb.MeetingCalendarControllerTest do
  @moduledoc """
  Tests for `GET /meetings/:id/invite.ics`.

  ## How these tests are written, and why

  Assertions on the document go through a parser — `ICalendar.from_ics/1`
  for the `VEVENT`, `PlatformTest.ICSContentLines` for everything that
  parser structurally cannot see — never a regex over the payload. Stage
  2 measured the two limits that matter here:

    * `from_ics/1` downcases `:status` and returns `:sequence` as a
      string, drops every calendar-level property, and never exposes
      `DTSTAMP`. An assertion against a field it does not populate is a
      silent `nil == nil`.
    * `from_ics/1` splits on `\\n` and trims `\\r`, so it cannot see line
      framing at all. Framing is asserted at the byte level or not
      claimed.

  ## What the two-fetch test does and does not prove

  The byte-identity assertion is the right assertion for "a re-fetch of
  an unchanged meeting is a no-op". It is **not** evidence of purity:
  stage 2 ran the obvious probe (swap `DTSTAMP` for `DateTime.utc_now/0`)
  and byte-identity stayed GREEN, because both renders land inside the
  same wall-clock second and `DTSTAMP` has second resolution.

  What does detect a wall-clock stamp — and what this module asserts
  instead — is equality of the served `DTSTAMP` against a `updated_at`
  seeded well in the past.
  """

  use PlatformWeb.ConnCase, async: true

  import Ecto.Query

  alias Platform.Meetings
  alias Platform.Meetings.CalendarFeed
  alias Platform.Meetings.CalendarLink
  alias Platform.Meetings.Meeting
  alias Platform.Repo
  alias Platform.Tasks
  alias PlatformTest.ICSContentLines

  @scheduled_start ~U[2026-08-15 14:00:00.000000Z]
  @scheduled_end ~U[2026-08-15 15:00:00.000000Z]

  # Deliberately far enough in the past that no wall clock could produce
  # it during the test run. See the moduledoc.
  @seeded_updated_at ~U[2026-06-01 09:30:00.000000Z]

  defp create_project! do
    org_id = Platform.TenancyFixtures.fabrikam_org_id()

    {:ok, project} =
      Tasks.create_project(%{
        name: "Calendar Feed Project #{System.unique_integer([:positive])}",
        org_id: org_id
      })

    project
  end

  defp create_meeting!(attrs \\ %{}) do
    project = Map.get_lazy(attrs, :project, fn -> create_project!() end)

    {:ok, meeting} =
      Meetings.create_meeting(%{
        project_id: project.id,
        name: Map.get(attrs, :name, "Calendar Kickoff #{System.unique_integer([:positive])}"),
        scheduled_start_at: Map.get(attrs, :scheduled_start_at, @scheduled_start),
        scheduled_end_at: Map.get(attrs, :scheduled_end_at, @scheduled_end)
      })

    meeting
  end

  # `updated_at` is autogenerated on insert, so the only way to pin it is
  # to write it behind the changeset.
  defp seed_updated_at!(%Meeting{} = meeting, %DateTime{} = at) do
    {1, _} =
      Meeting
      |> where([m], m.id == ^meeting.id)
      |> Repo.update_all(set: [updated_at: at])

    Meetings.get_meeting(meeting.id)
  end

  defp feed_path(%Meeting{} = meeting), do: Meetings.calendar_link_path(meeting)

  defp feed_path(meeting_id, token) when is_binary(meeting_id),
    do: "/meetings/#{meeting_id}/invite.ics?token=#{token}"

  defp one_event!(body) do
    events = ICalendar.from_ics(body)
    assert length(events) == 1
    hd(events)
  end

  describe "show/2 — a scheduled meeting" do
    test "serves the meeting's single VEVENT with its UID and times", %{conn: conn} do
      meeting = create_meeting!()

      conn = get(conn, feed_path(meeting))

      assert conn.status == 200

      event = one_event!(conn.resp_body)

      assert event.uid == CalendarFeed.uid(meeting)
      assert DateTime.compare(event.dtstart, @scheduled_start) == :eq
      assert DateTime.compare(event.dtend, @scheduled_end) == :eq
      assert event.summary == meeting.name
    end

    test "requires no session: a bare conn gets 200 and is handed no cookie" do
      meeting = create_meeting!()

      # NOT the `%{conn: conn}` from the case template and NOT a logged-in
      # user — this is the whole property. Google, Apple and Outlook fetch
      # a subscribed feed from their own servers with no cookie of ours. A
      # test that authenticated first would pass against an implementation
      # no calendar on earth can subscribe to.
      conn = get(Phoenix.ConnTest.build_conn(), feed_path(meeting))

      assert conn.status == 200
      assert Plug.Conn.get_resp_header(conn, "set-cookie") == []
      # Nothing in the pipeline may quietly fetch a session either. The
      # endpoint installs `Plug.Session` for every request, so the marker
      # is always PRESENT; `Plug.Conn.fetch_session/2` is what flips it to
      # `:done`. Asserting it is nil would be asserting nothing.
      refute conn.private[:plug_session_fetch] == :done
    end

    test "serves whatever the fetcher's Accept header says, including none" do
      meeting = create_meeting!()
      path = feed_path(meeting)

      # The `:calendar_feed` pipeline omits `plug(:accepts, ...)` on
      # purpose: Google, Apple and Outlook send inconsistent Accept
      # headers on a subscribed fetch, and an allowlist turns that into a
      # 406 that never reproduces in a browser. This pins that choice —
      # the omission is a decision, not an oversight, so it gets an
      # assertion rather than only a comment.
      for accept <- ["text/calendar", "*/*", "application/json", "text/html"] do
        conn =
          Phoenix.ConnTest.build_conn()
          |> Plug.Conn.put_req_header("accept", accept)
          |> get(path)

        assert conn.status == 200, "Accept: #{accept} returned #{conn.status}"
      end

      # And with no Accept header at all.
      bare =
        Phoenix.ConnTest.build_conn()
        |> Plug.Conn.delete_req_header("accept")
        |> get(path)

      assert bare.status == 200
    end

    test "two independent fetches agree on the UID and are byte-identical" do
      meeting = create_meeting!()
      path = feed_path(meeting)

      first = get(Phoenix.ConnTest.build_conn(), path)
      second = get(Phoenix.ConnTest.build_conn(), path)

      assert first.status == 200
      assert second.status == 200

      # The PARSED uid, not a format assertion: pinning a shape would pass
      # against an implementation that mints a fresh id on every request.
      assert one_event!(first.resp_body).uid == one_event!(second.resp_body).uid

      assert first.resp_body == second.resp_body
    end

    test "DTSTAMP is the row's updated_at, not the clock" do
      meeting = create_meeting!() |> seed_updated_at!(@seeded_updated_at)

      conn = get(Phoenix.ConnTest.build_conn(), feed_path(meeting))

      assert conn.status == 200

      # Equality against the seeded value, not merely "the two fetches
      # matched" — see the moduledoc on why byte-identity cannot detect a
      # wall-clock stamp. `from_ics/1` never exposes DTSTAMP, so this has
      # to be read off the wire form.
      assert ICSContentLines.value!(conn.resp_body, "DTSTAMP") ==
               Calendar.strftime(@seeded_updated_at, "%Y%m%dT%H%M%SZ")
    end
  end

  describe "show/2 — response headers" do
    test "is text/calendar, never cached, nosniff, inline" do
      meeting = create_meeting!()

      conn = get(Phoenix.ConnTest.build_conn(), feed_path(meeting))

      assert ["text/calendar; charset=utf-8"] =
               Plug.Conn.get_resp_header(conn, "content-type")

      assert [cache_control] = Plug.Conn.get_resp_header(conn, "cache-control")
      assert cache_control =~ "no-cache"
      assert cache_control =~ "no-store"

      # A cached response IS a stale snapshot — the failure the link was
      # built to avoid. Any max-age here is a defect.
      refute cache_control =~ "max-age"

      assert Plug.Conn.get_resp_header(conn, "pragma") == ["no-cache"]
      assert Plug.Conn.get_resp_header(conn, "x-content-type-options") == ["nosniff"]

      assert Plug.Conn.get_resp_header(conn, "content-disposition") == [
               ~s(inline; filename="invite.ics")
             ]
    end
  end

  describe "show/2 — the payload-vs-path guard" do
    test "a token minted for another meeting cannot read this one" do
      project = create_project!()
      meeting_a = create_meeting!(%{project: project, name: "Meeting A"})
      meeting_b = create_meeting!(%{project: project, name: "Meeting B"})

      # CONTROL. B is a fully valid, scheduled meeting that renders fine
      # with its OWN token. Without this the 404 below could be B failing
      # for some unrelated reason, and the test would credit the guard for
      # a red it did not cause.
      control = get(Phoenix.ConnTest.build_conn(), feed_path(meeting_b))
      assert control.status == 200
      assert one_event!(control.resp_body).uid == CalendarFeed.uid(meeting_b)

      # A's token, B's path. The only thing standing between them is the
      # payload-vs-path guard.
      conn =
        get(
          Phoenix.ConnTest.build_conn(),
          feed_path(meeting_b.id, CalendarLink.sign(meeting_a.id))
        )

      assert conn.status == 404
      assert conn.resp_body == ""
    end
  end

  describe "show/2 — the uniform 404" do
    test "every failure mode is byte-for-byte indistinguishable" do
      unscheduled = create_meeting!(%{scheduled_start_at: nil, scheduled_end_at: nil})
      unknown_id = Platform.Types.UUIDv7.generate()

      responses = [
        # No token at all.
        get(Phoenix.ConnTest.build_conn(), "/meetings/#{unscheduled.id}/invite.ics"),
        # A token that is not one of ours.
        get(Phoenix.ConnTest.build_conn(), feed_path(unscheduled.id, "not-a-real-token")),
        # A VALID token whose meeting does not exist — so the failure is
        # genuinely "row missing" and not another signature rejection.
        get(
          Phoenix.ConnTest.build_conn(),
          feed_path(unknown_id, CalendarLink.sign(unknown_id))
        ),
        # A real meeting, its own valid token, but no intended time.
        get(Phoenix.ConnTest.build_conn(), feed_path(unscheduled))
      ]

      assert Enum.map(responses, & &1.status) == [404, 404, 404, 404]

      # THE ACTUAL CLAIM. Four responses that are each 404 are not thereby
      # indistinguishable — four different bodies are all still 404. What
      # makes this not an existence oracle over meeting ids is that the
      # four responses are the SAME response.
      assert responses |> Enum.map(& &1.resp_body) |> Enum.uniq() == [""]
    end
  end
end
