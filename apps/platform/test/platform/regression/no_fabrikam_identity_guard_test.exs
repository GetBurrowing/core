defmodule Platform.Regression.NoFabrikamIdentityGuardTest do
  @moduledoc """
  Fabrikam is a client org on Rowan's installs. It is install DATA, not product
  identity, and a fresh install of an open-source Suite must not come up
  named, defaulted or styled after it (task 01a116de).

  This test scans the product surface AS TEXT for `~r/fabrikam/i` and holds an
  EXACT-COUNT allowlist: every file that may still carry the token, and how
  many times. It fails when

    * a file outside the allowlist carries the token (a new hit);
    * an allowlisted file carries MORE hits than its entry; or
    * an allowlisted file carries FEWER hits than its entry, or none at all
      (the ratchet: a stage that removes hits must shrink the list, so the
      allowlist can only ever get smaller).

  Scanned: `apps/*/lib/**/*.{ex,exs,heex,eex}`, `apps/*/config/**/*.exs`,
  the platform repo seeds, `apps/platform/assets/{css,js}`, `deployment/**`
  except `deployment/installer/tests/**` (the installer's own forbidden-word
  guards, which must keep the literal), and `services/*/src/**`. Tests,
  already-run migrations, intent_eval cassettes and docs are out of scope;
  `docs/architecture/install-identity-inventory.md` classifies every hit in
  the repo, and `scripts/install_identity_inventory.py --allowlist` prints
  the current map.

  The positive control feeds the same scanner a fixture file carrying the
  token and asserts the scanner names it, so a green run here cannot be a
  scanner that matches nothing.
  """
  use ExUnit.Case, async: true

  @repo_root Path.expand("../../../../..", __DIR__)
  @token ~r/fabrikam/i

  @scanned_globs [
    "apps/*/lib/**/*.{ex,exs,heex,eex}",
    "apps/*/config/**/*.exs",
    "apps/platform/priv/repo/seeds/**/*",
    "apps/platform/priv/repo/seeds.exs",
    "apps/platform/assets/{css,js}/**/*",
    "deployment/**/*",
    "services/*/src/**/*"
  ]

  @excluded_prefixes ["deployment/installer/tests/"]

  # Every scanned file allowed to carry the token, at its EXACT count. Each
  # entry names the stage of task 01a116de that removes it. Generated by
  # `python3 scripts/install_identity_inventory.py --allowlist`.
  @allowlist %{
    # KEEP (a-dep): published Android package id com.koboai.burrow
    "apps/platform/lib/platform/mobile/fcm_device.ex" => 4,
    # NO plan stage removes it yet (see the inventory)
    "deployment/schema/install-modules.md" => 3
  }

  defp scanned_files do
    @scanned_globs
    |> Enum.flat_map(&Path.wildcard(Path.join(@repo_root, &1)))
    |> Enum.uniq()
    |> Enum.filter(&File.regular?/1)
    |> Enum.reject(&excluded?/1)
    |> Enum.sort()
  end

  defp excluded?(abs) do
    rel = Path.relative_to(abs, @repo_root)

    Enum.any?(@excluded_prefixes, &String.starts_with?(rel, &1)) or
      String.contains?(rel, ["/__pycache__/", "/node_modules/"])
  end

  defp hits(abs), do: length(Regex.scan(@token, File.read!(abs)))

  # %{relative_path => hit_count} for every given file with at least one hit.
  defp counts(files) do
    for abs <- files, n = hits(abs), n > 0, into: %{} do
      {Path.relative_to(abs, @repo_root), n}
    end
  end

  # Files with a hit that the allowlist does not name.
  defp offenders(files) do
    files
    |> counts()
    |> Map.keys()
    |> Enum.reject(&Map.has_key?(@allowlist, &1))
    |> Enum.sort()
  end

  test "the scanned set is real and includes tenancy.ex" do
    files = scanned_files()
    assert length(files) > 100
    assert Path.join(@repo_root, "apps/platform/lib/platform/tenancy.ex") in files
  end

  test "no file outside the allowlist carries fabrikam" do
    found = offenders(scanned_files())

    assert found == [],
           "fabrikam found in files not on the allowlist (install identity belongs in the DB, " <>
             "not the code): " <> Enum.join(found, ", ")
  end

  test "no allowlisted file carries MORE fabrikam hits than its entry" do
    counts = counts(scanned_files())

    over =
      for {path, allowed} <- @allowlist,
          actual = Map.get(counts, path, 0),
          actual > allowed,
          do: "#{path}: #{actual} hits, allowlist says #{allowed}"

    assert over == [], "fabrikam hits grew: " <> Enum.join(over, "; ")
  end

  test "RATCHET: no allowlisted file carries FEWER hits than its entry, and none has zero" do
    counts = counts(scanned_files())

    under =
      for {path, allowed} <- Enum.sort(@allowlist),
          actual = Map.get(counts, path, 0),
          actual < allowed or actual == 0,
          do: "#{path}: #{actual} hits, allowlist says #{allowed}"

    assert under == [],
           "fabrikam hits shrank; lower the allowlist entry (or delete it at zero): " <>
             Enum.join(under, "; ")
  end

  @tag :tmp_dir
  test "POSITIVE CONTROL: a fixture carrying the token is named by the scanner, and only it",
       %{tmp_dir: dir} do
    fixture = Path.join(dir, "fixture.ex")
    File.write!(fixture, "# Fabrikam\n")

    assert offenders(scanned_files() ++ [fixture]) == [Path.relative_to(fixture, @repo_root)]
  end
end
