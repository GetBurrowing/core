defmodule Platform.Regression.PubSubTopicInventoryAuditTest do
  @moduledoc """
  Source-scan guard: every PubSub topic shape reachable in `apps/platform/lib`
  is classified in the inventory below, with a scope class saying who can
  receive it.

  ## What this defends

  A topic is a fan-out decision. `"chat:space:<id>"` reaches one space's
  subscribers; `"chat:spaces"` reaches every connected chat session in the
  install. The second kind is where cross-space bleed comes from, and the
  codebase has already paid for that twice (canvas bleed in task `019ffe65`,
  external rail re-broadening in `019ffebf`). Both were consumer-side misses on
  a topic whose blast radius nobody had written down.

  Nothing in the compiler makes an author think about blast radius before typing
  a new topic string. This scan does: adding a topic and not classifying it here
  fails the suite.

  ## Set equality, not subset

  `@topics` is compared to the scan for equality in BOTH directions.

    * A shape the scan finds that is not in `@topics` means a topic was added
      without a scope class. Red.
    * A shape in `@topics` the scan no longer finds means the topic was renamed
      or deleted and the classification is now fiction. Also red.

  A subset assertion would be satisfied by exactly the topic it exists to catch,
  because a forgotten topic was never in the expected list to begin with. The
  sibling guard `attention_broadcast_funnel_audit_test.exs` documents the
  incident where that shape went green over a real hole.

  ## Normalised shapes, not raw literals

  Every `\#{...}` interpolation collapses to `<id>`, and a literal ending in
  `":"` (the prefix half of a `<>` concatenation) gains one. So
  `"active_agent:\#{prev.id}"`, `"active_agent:\#{space.id}"` and
  `"active_agent:\#{space_id}"` are one entry, and `"files:project:" <> id`
  lands as `"files:project:<id>"`.

  This is deliberate: the inventory records topic SHAPE, which is what carries
  the scope decision. Renaming a local variable must not turn the suite red,
  and two spellings of one topic must not read as two topics.

  ## Non-vacuity

  A source scan that matches nothing passes forever. Three anchors stop that:

    1. `@min_topics` floors the discovered count well below today's number but
       far above zero, so a regex that stops matching fails loudly instead of
       going quietly green.
    2. `@scanner_anchors` names shapes that exist for independent reasons and
       span all four scan anchor kinds (topic-helper `def`, module attribute,
       `Phoenix.PubSub` call argument, `trigger_config` map). If the scan stops
       seeing one of those, the anchor test says which kind broke.
    3. The set-equality assertion itself can only pass with a scan that returns
      exactly 52 shapes, so the inventory cannot be satisfied by an empty scan.

  The inventory is hand-written from the stage-2 classification of task
  `019ffca8-6973-7bc2-bf5d-1fee7f2e64f3`. It is NOT generated from this scan:
  a list generated by the thing it is compared against can never disagree.

  ## Two scans, because topics enter by two doors

  `scan_topic_shapes/0` covers the colon-separated topics that reach a
  `Phoenix.PubSub` or `Endpoint` call, a `*_topic` helper or a `@*topic`
  attribute. `scan_responsibility_trigger_topics/0` covers the topics a
  `Platform.Responsibilities` handler declares in its `trigger_config`, which
  the Router subscribes to at boot from database rows rather than from a literal
  in a call site. The second set includes a dot-separated sentinel
  (`"platform.security.sweeper_only"`) that the first scan's grammar does not
  admit, which is why it is a separate scan and not a widened regex: widening
  the grammar to dots pulls in ten responsibility keys and prompt-template slugs
  that are not topics at all.

  Cheap by construction (`Path.wildcard` + `File.read!` + regex, no DB, no
  PubSub), so it runs in the default `mix test` set alongside its peers in
  `test/platform/regression/`.
  """

