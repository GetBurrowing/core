defmodule Platform.Changelog.ChangelogTest do
  @moduledoc "Tests for the Changelog context module."
  use Platform.DataCase, async: true

  alias Platform.Changelog
  alias Platform.Repo
  alias Platform.Tasks

  defp errors_on(changeset) do
    Ecto.Changeset.traverse_errors(changeset, fn {message, opts} ->
      Regex.replace(~r"%{(\w+)}", message, fn _, key ->
        opts |> Keyword.get(String.to_existing_atom(key), key) |> to_string()
      end)
    end)
  end

  # Helper to create a project + task for FK references
  defp create_task!(attrs \\ %{}) do
    {:ok, project} =
      Tasks.create_project(%{
        name: "Test Project #{System.unique_integer([:positive])}",
        repo_url: "https://github.com/test/repo"
      })

    {:ok, task} =
      Tasks.create_task(
        Map.merge(
          %{project_id: project.id, title: "Test task"},
          attrs
        )
      )

    {project, task}
  end

  # `Task.changeset/2` does not cast `:id` (it is autogenerated UUIDv7), so
  # tests that need a *specific* id — e.g. a deterministic 8-char prefix
  # collision — insert the struct directly.
  defp insert_task_with_id!(project, id, title) do
    Repo.insert!(%Platform.Tasks.Task{
      id: id,
      project_id: project.id,
      title: title,
      status: "backlog",
      priority: "medium"
    })
  end

  defp entry_attrs(overrides \\ %{}) do
    Map.merge(
      %{
        title: "Add changelog module",
        pr_number: System.unique_integer([:positive]),
        pr_url: "https://github.com/test/repo/pull/1",
        commit_sha: "abc123",
        author: "dev-user",
        tags: ["feature"],
        merged_at: DateTime.utc_now()
      },
      overrides
    )
  end

  describe "create_entry/1" do
    test "creates a changelog entry with valid attrs" do
      assert {:ok, entry} = Changelog.create_entry(entry_attrs())
      assert entry.title == "Add changelog module"
      assert entry.tags == ["feature"]
      assert entry.author == "dev-user"
    end

    test "requires title and merged_at" do
      assert {:error, changeset} = Changelog.create_entry(%{})
      errors = errors_on(changeset)
      assert "can't be blank" in errors.title
      assert "can't be blank" in errors.merged_at
    end

    test "enforces unique pr_number" do
      attrs = entry_attrs(%{pr_number: 42})
      assert {:ok, _} = Changelog.create_entry(attrs)
      assert {:error, changeset} = Changelog.create_entry(attrs)
      errors = errors_on(changeset)
      assert "has already been taken" in errors.pr_number
    end

    test "links to a task via task_id" do
      {_project, task} = create_task!()
      attrs = entry_attrs(%{task_id: task.id})
      assert {:ok, entry} = Changelog.create_entry(attrs)
      assert entry.task_id == task.id
    end

    test "broadcasts new entry on PubSub" do
      Changelog.subscribe()
      attrs = entry_attrs()
      {:ok, entry} = Changelog.create_entry(attrs)
      assert_receive {:new_changelog_entry, ^entry}
    end
  end

  describe "list_entries/1" do
    test "returns entries in reverse chronological order" do
      now = DateTime.utc_now()

      {:ok, old} =
        Changelog.create_entry(
          entry_attrs(%{title: "Old", merged_at: DateTime.add(now, -3600, :second)})
        )

      {:ok, new} =
        Changelog.create_entry(entry_attrs(%{title: "New", merged_at: now}))

      entries = Changelog.list_entries()
      ids = Enum.map(entries, & &1.id)
      assert List.first(ids) == new.id
      assert List.last(ids) == old.id
    end

    test "filters by tag" do
      {:ok, _feat} = Changelog.create_entry(entry_attrs(%{tags: ["feature"]}))
      {:ok, _fix} = Changelog.create_entry(entry_attrs(%{tags: ["fix"]}))

      entries = Changelog.list_entries(tag: "feature")
      assert length(entries) == 1
      assert hd(entries).tags == ["feature"]
    end

    test "paginates with :before cursor" do
      now = DateTime.utc_now()

      {:ok, _old} =
        Changelog.create_entry(
          entry_attrs(%{title: "Old", merged_at: DateTime.add(now, -7200, :second)})
        )

      {:ok, middle} =
        Changelog.create_entry(
          entry_attrs(%{title: "Middle", merged_at: DateTime.add(now, -3600, :second)})
        )

      {:ok, _new} =
        Changelog.create_entry(entry_attrs(%{title: "New", merged_at: now}))

      entries = Changelog.list_entries(before: middle.merged_at, limit: 10)
      assert length(entries) == 1
      assert hd(entries).title == "Old"
    end

    test "preloads task association" do
      {_project, task} = create_task!()
      {:ok, _entry} = Changelog.create_entry(entry_attrs(%{task_id: task.id}))

      [entry] = Changelog.list_entries()
      assert entry.task.id == task.id
      assert entry.task.title == "Test task"
    end
  end

  describe "group_by_date/1" do
    test "groups entries by date with human-readable labels" do
      today = DateTime.utc_now()
      yesterday = DateTime.add(today, -86_400, :second)
      old = DateTime.add(today, -86_400 * 3, :second)

      {:ok, e1} = Changelog.create_entry(entry_attrs(%{title: "Today PR", merged_at: today}))

      {:ok, e2} =
        Changelog.create_entry(entry_attrs(%{title: "Yesterday PR", merged_at: yesterday}))

      {:ok, e3} = Changelog.create_entry(entry_attrs(%{title: "Old PR", merged_at: old}))

      groups = Changelog.group_by_date([e1, e2, e3])

      labels = Enum.map(groups, fn {label, _} -> label end)
      assert "Today" in labels
      assert "Yesterday" in labels
      # Third label is a formatted date
      assert length(labels) == 3
    end
  end

  describe "parse_title/1" do
    test "parses feat: prefix" do
      assert {"add changelog", ["feature"]} = Changelog.parse_title("feat: add changelog")
    end

    test "parses fix: prefix" do
      assert {"crash on reload", ["fix"]} = Changelog.parse_title("fix: crash on reload")
    end

    test "parses scoped prefix like fix(chat):" do
      assert {"resolve error", ["fix"]} = Changelog.parse_title("fix(chat): resolve error")
    end

    test "parses refactor: as improvement" do
      assert {"clean up code", ["improvement"]} =
               Changelog.parse_title("refactor: clean up code")
    end

    test "returns empty tags for non-conventional title" do
      assert {"Update README", []} = Changelog.parse_title("Update README")
    end

    test "handles chore: prefix" do
      assert {"bump deps", ["chore"]} = Changelog.parse_title("chore: bump deps")
    end
  end

  describe "extract_task_id_from_branch/1" do
    test "returns nil for nil" do
      assert Changelog.extract_task_id_from_branch(nil) == nil
    end

    test "returns nil for unrelated branch names" do
      assert Changelog.extract_task_id_from_branch("feat/changelog") == nil
      assert Changelog.extract_task_id_from_branch("main") == nil
    end

    test "extracts full UUID from task/ prefix" do
      {_project, task} = create_task!()
      branch = "task/#{task.id}"
      assert Changelog.extract_task_id_from_branch(branch) == task.id
    end

    test "extracts short prefix and finds matching task" do
      {_project, task} = create_task!()
      # Extract the first 8 chars of the UUID
      prefix = task.id |> String.slice(0, 8)
      branch = "task/#{prefix}"
      assert Changelog.extract_task_id_from_branch(branch) == task.id
    end

    test "returns nil when prefix matches no task" do
      assert Changelog.extract_task_id_from_branch("task/00000000") == nil
    end
  end

  # Regression coverage for the 8-hex-prefix collision that mis-attributed
  # PR #604 (branch `task/019f9b11-97d7`) to task `019f9b11-3bde…`, falsely
  # passing that task's `pr_merged` validation. Two defects, both covered
  # here: the fallback regex truncated the branch's disambiguator back to 8
  # chars, and `find_task_by_prefix/1` returned an arbitrary row on a
  # multi-row match instead of failing closed.
  #
  # Task ids are UUIDv7 (time-ordered), so tasks filed seconds apart really do
  # share 8-char prefixes; these fixtures use literal colliding ids rather
  # than generated ones so the collision is deterministic.
  describe "extract_task_id_from_branch/1 with colliding id prefixes" do
    @collide_a "019f9b11-97d7-7e77-af5c-a69c699280a2"
    @collide_b "019f9b11-3bde-71e3-8ba2-f18adf9c6f9d"

    setup do
      {project, _task} = create_task!()

      a = insert_task_with_id!(project, @collide_a, "RuntimeChannel capability model")
      b = insert_task_with_id!(project, @collide_b, "Fix GitHub webhook signature bypass")

      %{project: project, task_a: a, task_b: b}
    end

    test "disambiguated branch resolves to its own task, not its twin", ctx do
      # The exact PR #604 scenario. Before the fix both of these returned
      # whichever row Postgres happened to hand back first.
      assert Changelog.extract_task_id_from_branch("task/019f9b11-97d7") == ctx.task_a.id
      assert Changelog.extract_task_id_from_branch("task/019f9b11-3bde") == ctx.task_b.id
    end

    # Detects the regex half in isolation, but passed against the fully
    # unfixed code — there the truncated `019f9b11` lookup happened to return
    # `-97d7` from an unordered `limit: 1`. Treat as a partial detector.
    test "disambiguated branch with a descriptive suffix still resolves", ctx do
      assert Changelog.extract_task_id_from_branch("task/019f9b11-97d7-runtime-channel") ==
               ctx.task_a.id
    end

    test "genuinely ambiguous bare prefix returns nil rather than picking one" do
      # Both fixture tasks match `019f9b11%`. Failing closed is deliberate: a
      # wrong attribution silently satisfies another task's deploy gate.
      assert Changelog.extract_task_id_from_branch("task/019f9b11") == nil
    end

    test "ambiguity logs a warning naming the prefix" do
      log =
        ExUnit.CaptureLog.capture_log(fn ->
          assert Changelog.extract_task_id_from_branch("task/019f9b11") == nil
        end)

      assert log =~ "ambiguous"
      assert log =~ "019f9b11"
    end

    # GUARD, not proof: passes against the unfixed code too. Its job is to
    # stop the fix from over-correcting the already-working full-UUID path.
    test "full UUID still resolves even when the 8-char prefix is ambiguous", ctx do
      assert Changelog.extract_task_id_from_branch("task/#{@collide_a}") == ctx.task_a.id
      assert Changelog.extract_task_id_from_branch("task/#{@collide_b}") == ctx.task_b.id
    end

    # GUARD, not proof: passes against the unfixed code too. Fail-closed must
    # only bite on real collisions, not on every short prefix.
    test "an unambiguous 8-char prefix still resolves", ctx do
      solo = insert_task_with_id!(ctx.project, "019f0000-1111-7222-8333-444444444444", "Solo")

      assert Changelog.extract_task_id_from_branch("task/019f0000") == solo.id
    end

    test "body references honour the disambiguator too", ctx do
      assert Changelog.extract_task_id_from_body("Task: 019f9b11-97d7") == ctx.task_a.id
      assert Changelog.extract_task_id_from_body("Task: 019f9b11") == nil
    end

    # ── Task 019fb949: the round trip a full-uuid branch name must survive ──
    # The real incident pair — filed eleven seconds apart, sharing `019fb90f`.
    @incident_a "019fb90f-36e3-7bff-a6f1-69cd689faa59"
    @incident_b "019fb90f-6226-7c68-9ec2-7bbc9378e8e2"

    defp incident_pair(project) do
      {insert_task_with_id!(project, @incident_a, "Colliding task A"),
       insert_task_with_id!(project, @incident_b, "Colliding task B")}
    end

    # The dispatch renderer is being changed to emit `task/<full uuid>` for
    # NON-stack tasks too. These pin the reading end of that contract with the
    # real incident pair (`019fb90f-36e3-…` and `019fb90f-6226-…`, filed eleven
    # seconds apart, sharing `019fb90f`).
    #
    # GUARDS, not proofs of the renderer defect — they pass against the current
    # code, because the reading end was already repaired for the 019f9b11 pair
    # above. Their job is to stop the reading end from regressing while the
    # writing end is changed, and to record what the old 8-char scheme could
    # never have done (see the last test in this group).
    test "each full-uuid incident branch resolves to its own task, no cross-attribution", ctx do
      {a, b} = incident_pair(ctx.project)

      assert Changelog.extract_task_id_from_branch("task/" <> a.id) == a.id
      assert Changelog.extract_task_id_from_branch("task/" <> b.id) == b.id
    end

    test "a descriptive suffix on a full-uuid branch does not derail the parse", ctx do
      {a, _b} = incident_pair(ctx.project)

      assert Changelog.extract_task_id_from_branch("task/#{a.id}-runtime-channel") == a.id
    end

    test "the legacy 8-char slug the incident pair shared resolves to nobody", ctx do
      # Not a nice-to-have: under the old naming scheme BOTH of these tasks
      # pushed `task/019fb90f`, so deploy attribution for either one was
      # already impossible — `find_task_by_prefix/1` fails closed rather than
      # crediting a coin-flip twin. This is the state the renderer change
      # exits, not a risk it avoids.
      {_a, _b} = incident_pair(ctx.project)

      assert Changelog.extract_task_id_from_branch("task/019fb90f") == nil
    end
  end

  describe "extract_task_id_from_body/1" do
    test "returns nil for nil" do
      assert Changelog.extract_task_id_from_body(nil) == nil
    end

    test "extracts task ID from 'Task: <uuid>' pattern" do
      {_project, task} = create_task!()
      body = "Some text\n\nTask: #{task.id}\n\nMore text"
      assert Changelog.extract_task_id_from_body(body) == task.id
    end
  end

  # ── UUID boundary (task 019fa129 stage 4) ────────────────────────────────
  # The 16-character case is the load-bearing one: `Ecto.UUID.cast/1` accepts
  # any 16-byte binary, so a test built from "higgins" alone is green against
  # the bug these guards fix.
  describe "UUID boundary: get_entry/1" do
    test "returns nil for a malformed id rather than raising" do
      assert Changelog.get_entry("higgins") == nil
      assert Changelog.get_entry("higginshigginsxx") == nil
      assert Changelog.get_entry("") == nil
    end
  end
end
