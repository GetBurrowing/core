defmodule PlatformWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :platform

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_platform_session",
    signing_salt: "LVkhtRt/",
    same_site: "Lax",
    http_only: true
  ]

  socket "/runtime/ws", PlatformWeb.RuntimeSocket,
    websocket: [timeout: 120_000, check_origin: false],
    longpoll: false

  # The install's agent host dials out to core here (task 01a10322 stage 2).
  # The token travels in the `x-agent-host-token` header, hence `:x_headers`.
  socket "/agent-host", PlatformWeb.AgentHostSocket,
    websocket: [timeout: 120_000, check_origin: false, connect_info: [:x_headers]],
    longpoll: false

  # `:user_agent` is here for `PlatformWeb.ShellLive`, which names the browser
  # in the blocked-notifications row on `/inbox` (task 019ffb7b stage 4). The
  # dead render reads the header off the conn either way; without this the
  # CONNECTED mount would read nil and quietly replace the browser-specific
  # instruction with the generic one a moment after the page settles.
  socket("/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:user_agent, session: @session_options]],
    longpoll: [connect_info: [:user_agent, session: @session_options]]
  )

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug(Plug.Static,
    at: "/",
    from: :platform,
    gzip: not code_reloading?,
    only: PlatformWeb.static_paths(),
    raise_on_missing_only: code_reloading?
  )

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket("/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket)
    plug(Phoenix.LiveReloader)
    plug(Phoenix.CodeReloader)
  end

  plug(Plug.RequestId)
  plug(PlatformWeb.Plugs.RewriteRemoteIp)
  # `log:` keeps Phoenix's per-request "GET /path" line, at its default
  # :info, for every path except the single-use vault fetch: that line prints
  # the RAW request path, and `:filter_parameters` only filters the params
  # map, so the ticket token would otherwise reach the log while it is still
  # redeemable (task 01a131c5).
  plug(Plug.Telemetry,
    event_prefix: [:phoenix, :endpoint],
    log: {__MODULE__, :request_log_level, []}
  )

  # `RawBodyPaths` delegates to `Plug.Parsers` for everything except the
  # routes that stream their own request body (the presigned attachment
  # upload). See the module doc: without it, a JSON upload silently stored
  # zero bytes while a PNG upload of the same shape worked.
  plug(PlatformWeb.Plugs.RawBodyPaths,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library(),
    body_reader: {PlatformWeb.Plugs.CacheBodyReader, :read_body, []}
  )

  plug(Plug.MethodOverride)
  plug(Plug.Head)
  # SessionCookieDomain wraps Plug.Session to inject a runtime-configured cookie
  # `Domain` (SESSION_COOKIE_DOMAIN, prod-only) on the Set-Cookie WRITE path.
  # The `@session_options` attribute and both socket `connect_info` reads above
  # stay untouched: `Domain` only matters when writing the cookie, not when the
  # LiveView socket reads/verifies the already-signed cookie. See the plug.
  plug(PlatformWeb.Plugs.SessionCookieDomain, @session_options)
  plug(PlatformWeb.Router)

  @doc false
  # Plug.Telemetry `log:` callback; see the plug above.
  def request_log_level(%Plug.Conn{path_info: ["vault", "fetch" | _]}), do: false
  def request_log_level(_conn), do: :info
end
