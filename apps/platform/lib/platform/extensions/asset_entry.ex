defmodule Platform.Extensions.AssetEntry do
  @moduledoc """
  Renders the two build inputs a with-modules release host generates from its
  configured extensions' `assets/0` (ADR 0055, task 01a0ee08 stage 3):

    * the `@extensions` esbuild entry: a JS file whose default export merges
      every module's hook map, which core's `js/hooks/index.js` spreads in;
    * a wrapper stylesheet: core's `assets/css/app.css`, then each module's
      stylesheet, then a Tailwind `@source` for each module's sources.

  Paths inside the generated files are relative to the file itself, so a
  generated file is correct wherever the tree is checked out (a Docker build
  stage, a CI runner). Nothing is written into apps/platform: the
  without-modules build aliases `@extensions` to `js/extensions/none.js` and
  compiles `app.css` directly. See
  `0055-extension-contract-and-build-time-modules.md § 4. Assets`.

  Pure: `js/2` and `css/3` return iodata-free strings; `mix
  platform.extensions.assets` writes them.
  """

  @header "Generated by `mix platform.extensions.assets` (ADR 0055). Do not edit."

  @doc """
  The `@extensions` entry for `assets` (`Platform.Extensions.assets/0`'s
  shape), to be written into `out_dir`. With no module hooks it is an empty
  map, exactly `js/extensions/none.js`.
  """
  @spec js([{module(), map()}], String.t()) :: String.t()
  def js(assets, out_dir) do
    hooks =
      for {{_ext, %{js_hooks: path}}, index} <- Enum.with_index(assets),
          is_binary(path),
          do: {"ext#{index}", relative(path, out_dir)}

    imports = Enum.map(hooks, fn {name, path} -> ~s(import #{name} from "#{path}"\n) end)
    spread = Enum.map_join(hooks, "", fn {name, _} -> "  ...#{name},\n" end)

    "// #{@header}\n" <> Enum.join(imports) <> "\nexport default {\n" <> spread <> "}\n"
  end

  @doc """
  The wrapper stylesheet for `assets`: imports `core_css` (core's
  `assets/css/app.css`) first, then each module's `:css`, then adds an
  `@source` for each module's `:tailwind_sources`, all relative to `out_dir`.
  """
  @spec css([{module(), map()}], String.t(), String.t()) :: String.t()
  def css(assets, core_css, out_dir) do
    module_css =
      for {_ext, %{css: path}} <- assets,
          is_binary(path),
          do: ~s(@import "#{relative(path, out_dir)}";\n)

    sources =
      for {_ext, %{tailwind_sources: paths}} <- assets,
          path <- paths,
          do: ~s(@source "#{relative(path, out_dir)}";\n)

    "/* #{@header} */\n" <>
      ~s(@import "#{relative(core_css, out_dir)}";\n) <>
      Enum.join(module_css) <> Enum.join(sources)
  end

  defp relative(path, out_dir) do
    rel = Path.relative_to(Path.expand(path), Path.expand(out_dir), force: true)
    if String.starts_with?(rel, "."), do: rel, else: "./" <> rel
  end
end
