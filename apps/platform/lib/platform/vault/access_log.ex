defmodule Platform.Vault.AccessLog do
  @moduledoc """
  An immutable access log entry for Vault credential operations.

  Append-only — no changeset, never updated or deleted.
  Uses a UUID PK (binary_id) generated by Ecto before insert.

  Actions: use | read | create | update | rotate | revoke | denied

  ## Outliving the credential

  A log entry survives the credential it describes. `credential_id` is nullable
  and the foreign key is `ON DELETE SET NULL`, so destroying a credential leaves
  its history in place with the association nulled rather than cascading the
  rows away — see
  `priv/repo/migrations/20260725220000_retain_vault_access_log_on_credential_delete.exs`.

  Because a null `credential_id` would make an entry unreadable, `credential_slug`
  and `credential_scope_type` are denormalised copies written at insert time by
  `Platform.Vault`. They are plain columns, not references: their whole purpose is
  to stay meaningful after the credential row is gone, so query post-deletion
  history by `credential_slug`.
  """

  use Ecto.Schema

  @primary_key {:id, Platform.Types.UUIDv7, autogenerate: true}
  @foreign_key_type :binary_id

  schema "vault_access_log" do
    belongs_to(:credential, Platform.Vault.Credential)

    # Denormalised at write time so the entry stays readable once credential_id
    # is nulled by ON DELETE SET NULL.
    field(:credential_slug, :string)
    field(:credential_scope_type, :string)

    field(:accessor_type, :string)
    field(:accessor_id, :binary_id)
    field(:action, :string)
    field(:metadata, :map, default: %{})

    timestamps(type: :utc_datetime_usec, updated_at: false)
  end
end
