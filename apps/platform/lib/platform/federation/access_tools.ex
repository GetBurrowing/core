defmodule Platform.Federation.AccessTools do
  @moduledoc "Definitions for the optional access bundle; human clicks alone authorize changes."
  def definitions do
    [
      definition(
        "access_explain",
        "Explain whether a person or agent can see a resource, using the same view-as scope as the Access panel.",
        %{
          target: param("object", "{type: user|agent, id: user UUID or runtime UUID}."),
          resource: param("object", "{type: project|space|canvas|memory_node, id: UUID}."),
          permission: %{
            type: "string",
            description: "Permission to explain; defaults to the resource read permission."
          }
        },
        "allowed, sources, in_view_as",
        "When an admin asks why someone can or cannot see a resource."
      ),
      definition(
        "access_propose",
        "Show a server-built access change card with everyone who will lose access. Changes await a human clicking Apply.",
        %{
          space_id: param("string", "Space UUID where this agent participates."),
          options:
            param(
              "array",
              "One to three options, each {key, ops: [{action: grant|deny|revoke, principal: [user|agent|role,id], permission, resource: [project|space|canvas|memory_node,id], id?}]}. Labels are generated by the server."
            )
        },
        "proposal_id, canvas_id, view_url, count, conflicts",
        "Before changing access; let the human review the card."
      ),
      definition(
        "access_apply",
        "Read whether a proposed access change was applied. This tool never applies a change; only a human click on Apply does that.",
        %{proposal_id: param("string", "Proposal UUID returned by access_propose.")},
        "state (awaiting_human_approval, applied, cancelled, stale, failed or undone), change_id, approver, time, view_url",
        "Check whether the human has clicked Apply."
      ),
      definition(
        "access_undo",
        "Propose undoing one access change. Shows an undo card; a human must click Apply to restore access.",
        %{
          change_id: param("string", "Grant change UUID."),
          space_id: param("string", "Space UUID where this agent participates.")
        },
        "proposal_id, canvas_id, view_url, count, conflicts",
        "When an admin asks to undo a prior access change."
      )
    ]
  end

  defp param(type, description), do: %{type: type, required: true, description: description}

  defp definition(name, description, parameters, returns, usage),
    do: %{
      name: name,
      description: description,
      parameters: parameters,
      returns: returns,
      limitations:
        "Requires access.manage and the optional access module. Missing and unreadable resources both return not_found. No agent can approve or apply a change.",
      when_to_use: usage
    }
end
