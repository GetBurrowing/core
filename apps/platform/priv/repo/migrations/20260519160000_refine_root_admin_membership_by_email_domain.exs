defmodule Platform.Repo.Migrations.RefineRootAdminMembershipByEmailDomain do
  @moduledoc """
  Replace the hardcoded admin email allowlist (PR #394's
  `20260519143630_backfill_root_org_memberships.exs`) with an email-domain
  rule so the original operator's new hires automatically inherit `:admin` on the root org
  without a per-person migration.

  ## Rule

      WHERE LOWER(email) LIKE '%@<operator domain>'

  Anchored on the literal `@<operator domain>` suffix (the original
  operator's email domain, spelled out in the SQL below) to avoid the
  obvious spoof / subdomain traps:

    * `<operator domain>@gmail.com` → does NOT match (ends in `@gmail.com`)
    * `alice@us.<operator domain>` → does NOT match (subdomain in the middle)
    * `Alice@<OPERATOR DOMAIN>`    → matches (LOWER normalizes the host)
    * `alex@<operator domain>` → matches

  ## Idempotency: ADDITIVE ONLY

  Promotes matching emails to `:admin` via `ON CONFLICT (user_id, org_id)
  DO UPDATE`. Does **not** downgrade non-matching admins — a manually
  granted admin (or anyone an admin elevated post-#394) stays admin until a
  separate operation strips them. Re-running is safe: already-admin rows
  are unchanged by the upsert.

  The membership row is inserted at `:member` if it doesn't already
  exist; the upsert immediately re-states it to `:admin`. The net effect
  is "ensure this user has an admin row in the root org" without needing two
  passes.

  ## FROZEN: do not edit this file to match the runtime rule

  Task 01a081c2 stage 2 moved the ongoing rule to
  `config :platform, :admin_email_domain` read through
  `Platform.Tenancy.derive_role_from_email/1` on every login. The SQL below
  is operator-specific HISTORY and is deliberately left hardcoded. It has already
  run on every install, `schema_migrations` records only the version number
  and never the file's contents, and on a fresh database it runs before any
  user row exists and matches nothing. Editing it would change what a future
  fresh migrate runs while leaving recorded history untouched, and reading
  application config from a migration would bake one install's configuration
  into another install's schema history. Nothing here is in lockstep with
  anything any more.

  ## Literals matched by digest (task 01a14b9e stage 5)

  The root slug and the email domain were literals in this SQL. Both are
  now compared by sha256 against the literal's digest, so the public tree
  does not spell them. The domain predicate takes the text after the LAST
  `@` of the lowercased address, which is the domain exactly when the
  address ends in `@<domain>` (a domain carries no `@`), so it selects the
  same users as the `LIKE '%@<domain>'` it replaces; the slug predicate
  selects the same org. This is the one edit made to the frozen SQL: it
  changes no row on any database, fresh or existing.

  ## Hazard on a fresh install whose root org is not the original slug

  Found during recon for 01a081c2, not live anywhere today. The INSERT's
  org_id is a subquery on the original operator's root slug and
  `org_memberships.org_id` is `null: false`
  (`20260519143610_create_org_memberships.exs:46-49`). On a fresh database
  whose root org never carries that slug, if even one user with an
  address on the operator domain exists at migrate time, that subquery returns no row,
  the INSERT writes `org_id = NULL`, and the migration aborts on the NOT-NULL
  constraint. The ordinary case is safe only because no user row exists yet
  when this runs.

  Contractors temporarily on an admin-domain address should be denylisted via
  the roles_locked_at column. See migration
  20260519220000_add_roles_locked_at_to_org_memberships (stage 3 of the
  original task).

  ## Reversal

  `down/0` is a no-op. Reversing the promotion safely would require
  knowing each user's prior role; that history is not preserved here.
  If you need to roll back, restore from a backup or run a targeted
  downgrade manually.
  """

  use Ecto.Migration

  def up do
    Ecto.Adapters.SQL.query!(
      Platform.Repo,
      """
      INSERT INTO org_memberships (id, user_id, org_id, role, inserted_at, updated_at)
      SELECT
        gen_random_uuid(),
        u.id,
        (SELECT id FROM orgs WHERE encode(sha256(convert_to(slug, 'UTF8')), 'hex') = '9cfdc719f125bfd24830658f109d785ecca57a0c05022add0f6cf4aaec5dc25c'),
        'admin',
        NOW(),
        NOW()
      FROM users u
      WHERE encode(sha256(convert_to(substring(LOWER(u.email) from '@([^@]*)$'), 'UTF8')), 'hex') =
            '5dea22a579e9477122312d9f7269eabfa8147527a8d24738683f6b6734487560'
      ON CONFLICT (user_id, org_id) DO UPDATE
        SET role = 'admin', updated_at = NOW()
      """,
      []
    )
  end

  def down do
    # No-op — this migration only promotes; reversing would require knowing prior state.
    :ok
  end
end
